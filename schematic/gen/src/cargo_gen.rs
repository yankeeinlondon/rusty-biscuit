    fn dependency_path(content: &str, dependency: &str) -> String {
        let parsed: toml_crate::Table = toml_crate::from_str(content).expect("valid TOML");
        parsed["dependencies"][dependency]["path"]
            .as_str()
            .expect("path is a string")
            .to_string()
    }

