//! Type reference and primitive type definitions.

use schemars::generate::SchemaSettings;
use serde_json::{Value, json};

/// Primitive types.
///
/// Represents the basic building-block types that map to Rust primitives.
///
/// ## Examples
///
/// ```
/// use schematic_define::models::PrimitiveType;
///
/// let primitives = vec![
///     PrimitiveType::String,
///     PrimitiveType::Integer,
///     PrimitiveType::Number,
///     PrimitiveType::Boolean,
///     PrimitiveType::Bytes,
///     PrimitiveType::Json,
/// ];
///
/// assert_eq!(primitives.len(), 6);
/// ```
#[non_exhaustive]
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, serde::Serialize, serde::Deserialize)]
pub enum PrimitiveType {
    /// UTF-8 string.
    String,
    /// 64-bit signed integer.
    Integer,
    /// 64-bit floating-point number.
    Number,
    /// Boolean true/false.
    Boolean,
    /// Raw bytes (binary data).
    Bytes,
    /// Arbitrary JSON value (serde_json::Value).
    Json,
    /// `i8`.
    I8,
    /// `i16`.
    I16,
    /// `i32`.
    I32,
    /// `i128`.
    I128,
    /// `isize`.
    Isize,
    /// `u8`.
    U8,
    /// `u16`.
    U16,
    /// `u32`.
    U32,
    /// `u64`.
    U64,
    /// `u128`.
    U128,
    /// `usize`.
    Usize,
    /// `f32`.
    F32,
    /// `char`.
    Char,
    /// `()`, serialized as JSON null.
    Unit,
}

impl PrimitiveType {
    /// Fully qualified Rust spelling. `Integer` is `i64` and `Number` is `f64`.
    pub fn rust_path(self) -> &'static str {
        match self {
            Self::String => "::std::string::String",
            Self::Integer => "i64",
            Self::Number => "f64",
            Self::Boolean => "bool",
            Self::Bytes => "::std::vec::Vec<u8>",
            Self::Json => "::serde_json::Value",
            Self::I8 => "i8",
            Self::I16 => "i16",
            Self::I32 => "i32",
            Self::I128 => "i128",
            Self::Isize => "isize",
            Self::U8 => "u8",
            Self::U16 => "u16",
            Self::U32 => "u32",
            Self::U64 => "u64",
            Self::U128 => "u128",
            Self::Usize => "usize",
            Self::F32 => "f32",
            Self::Char => "char",
            Self::Unit => "()",
        }
    }

    /// Inline wire schema, as generated by schemars with OpenAPI 3.0 settings.
    pub fn wire_schema(self) -> Value {
        match self {
            Self::String => inline::<String>(),
            Self::Integer => inline::<i64>(),
            Self::Number => inline::<f64>(),
            Self::Boolean => inline::<bool>(),
            Self::Bytes => inline::<Vec<u8>>(),
            Self::Json => inline::<Value>(),
            Self::I8 => inline::<i8>(),
            Self::I16 => inline::<i16>(),
            Self::I32 => inline::<i32>(),
            Self::I128 => inline::<i128>(),
            Self::Isize => inline::<isize>(),
            Self::U8 => inline::<u8>(),
            Self::U16 => inline::<u16>(),
            Self::U32 => inline::<u32>(),
            Self::U64 => inline::<u64>(),
            Self::U128 => inline::<u128>(),
            Self::Usize => inline::<usize>(),
            Self::F32 => inline::<f32>(),
            Self::Char => inline::<char>(),
            Self::Unit => inline::<()>(),
        }
    }
}

fn inline<T: schemars::JsonSchema>() -> Value {
    let mut schema = SchemaSettings::openapi3().into_generator().into_root_schema_for::<T>().to_value();
    if let Some(object) = schema.as_object_mut() {
        object.remove("$schema");
        object.remove("title");
    }
    schema
}

/// A reference to a type.
///
/// Represents various ways to reference types: primitives, arrays, maps,
/// named types, and schema combinators (oneOf, anyOf, allOf).
///
/// ## Examples
///
/// ```
/// use schematic_define::models::{TypeRef, PrimitiveType};
///
/// // Primitive type
/// let string_ref = TypeRef::Primitive(PrimitiveType::String);
///
/// // Array of strings
/// let string_array = TypeRef::Array(Box::new(TypeRef::Primitive(PrimitiveType::String)));
///
/// // Map with string values
/// let string_map = TypeRef::Map(Box::new(TypeRef::Primitive(PrimitiveType::String)));
///
/// // Named type reference
/// let user_ref = TypeRef::Named("User".to_string());
///
/// // Optional string
/// let optional_string = TypeRef::Optional(Box::new(TypeRef::Primitive(PrimitiveType::String)));
///
/// // OneOf combinator
/// let one_of = TypeRef::OneOf(vec![
///     TypeRef::Named("Cat".to_string()),
///     TypeRef::Named("Dog".to_string()),
/// ]);
/// ```
#[non_exhaustive]
#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
pub enum TypeRef {
    /// A primitive type.
    Primitive(PrimitiveType),
    /// An array of items of the inner type.
    Array(Box<TypeRef>),
    /// A map (object) with string keys and values of the inner type.
    Map(Box<TypeRef>),
    /// A map whose Rust key type is not `String` but serializes as a JSON
    /// object key. The wire form equals [`TypeRef::Map`]; `key` is the Rust
    /// spelling, because a key type has no schema component of its own.
    KeyedMap {
        /// Rust spelling of the key type.
        key: String,
        /// Value type.
        value: Box<TypeRef>,
    },
    /// A reference to a named type (struct, enum, or alias).
    Named(String),
    /// OpenAPI `oneOf` - exactly one of the listed types.
    OneOf(Vec<TypeRef>),
    /// OpenAPI `anyOf` - one or more of the listed types.
    AnyOf(Vec<TypeRef>),
    /// OpenAPI `allOf` - combines all listed types (intersection).
    AllOf(Vec<TypeRef>),
    /// An optional wrapper around another type.
    Optional(Box<TypeRef>),
    /// Unknown or unsupported type.
    Unknown,
}

impl TypeRef {
    /// Wire schema with nominal component references and container shape.
    pub fn wire_schema(&self) -> Value {
        match self {
            Self::Primitive(primitive) => primitive.wire_schema(),
            Self::Named(name) => json!({"$ref": format!("#/components/schemas/{name}")}),
            Self::Array(item) => json!({"type": "array", "items": item.wire_schema()}),
            Self::Map(value) | Self::KeyedMap { value, .. } => json!({"type": "object", "additionalProperties": value.wire_schema()}),
            Self::Optional(inner) => {
                let mut schema = schemars::json_schema!({"anyOf": [inner.wire_schema(), {"type": "null"}]});
                for mut transform in SchemaSettings::openapi3().transforms {
                    transform.transform(&mut schema);
                }
                schema.to_value()
            }
            Self::OneOf(types) => json!({"oneOf": types.iter().map(Self::wire_schema).collect::<Vec<_>>()}),
            Self::AnyOf(types) => json!({"anyOf": types.iter().map(Self::wire_schema).collect::<Vec<_>>()}),
            Self::AllOf(types) => json!({"allOf": types.iter().map(Self::wire_schema).collect::<Vec<_>>()}),
            Self::Unknown => json!({}),
        }
    }

    /// Rust spelling, with `resolve` supplying each component's Rust path.
    /// `None` when a name is unresolved or the form has no Rust type
    /// (compositions and `Unknown`).
    pub(crate) fn rust_path_with(&self, resolve: &dyn Fn(&str) -> Option<String>) -> Option<String> {
        Some(match self {
            Self::Primitive(primitive) => primitive.rust_path().to_owned(),
            Self::Named(name) => resolve(name)?,
            Self::Array(item) => format!("::std::vec::Vec<{}>", item.rust_path_with(resolve)?),
            Self::Optional(inner) => format!("::std::option::Option<{}>", inner.rust_path_with(resolve)?),
            Self::Map(value) => format!("::std::collections::HashMap<::std::string::String, {}>", value.rust_path_with(resolve)?),
            Self::KeyedMap { key, value } => format!("::std::collections::HashMap<{key}, {}>", value.rust_path_with(resolve)?),
            Self::OneOf(_) | Self::AnyOf(_) | Self::AllOf(_) | Self::Unknown => return None,
        })
    }

    /// Every component name this reference mentions, in encounter order.
    pub fn names(&self) -> Vec<&str> {
        match self {
            Self::Named(name) => vec![name.as_str()],
            Self::Array(inner) | Self::Optional(inner) | Self::Map(inner) | Self::KeyedMap { value: inner, .. } => inner.names(),
            Self::OneOf(types) | Self::AnyOf(types) | Self::AllOf(types) => types.iter().flat_map(Self::names).collect(),
            Self::Primitive(_) | Self::Unknown => vec![],
        }
    }

    /// Every component name this reference mentions, mutably, at any
    /// nesting depth; the same names as [`Self::names`], in the same order.
    // OpenAPI import renames components through it.
    #[cfg_attr(not(feature = "openapi"), allow(dead_code))]
    pub(crate) fn names_mut(&mut self) -> Vec<&mut String> {
        match self {
            Self::Named(name) => vec![name],
            Self::Array(inner) | Self::Optional(inner) | Self::Map(inner) | Self::KeyedMap { value: inner, .. } => inner.names_mut(),
            Self::OneOf(types) | Self::AnyOf(types) | Self::AllOf(types) => types.iter_mut().flat_map(Self::names_mut).collect(),
            Self::Primitive(_) | Self::Unknown => vec![],
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn primitive_type_debug_clone_eq() {
        let prim = PrimitiveType::String;
        #[allow(clippy::clone_on_copy)]
        let cloned = prim.clone();
        assert_eq!(prim, cloned);
        assert_eq!(format!("{:?}", prim), "String");
    }

    #[test]
    fn primitive_type_copy() {
        let original = PrimitiveType::Integer;
        let copied = original;
        assert_eq!(original, copied);
    }

    #[test]
    fn primitive_type_hash() {
        use std::collections::HashSet;
        let mut set = HashSet::new();
        set.insert(PrimitiveType::String);
        set.insert(PrimitiveType::Integer);
        assert_eq!(set.len(), 2);
        assert!(set.contains(&PrimitiveType::String));
    }

    #[test]
    fn primitive_type_all_variants() {
        let variants = [
            PrimitiveType::String,
            PrimitiveType::Integer,
            PrimitiveType::Number,
            PrimitiveType::Boolean,
            PrimitiveType::Bytes,
            PrimitiveType::Json,
        ];
        assert_eq!(variants.len(), 6);
    }

    #[test]
    fn type_ref_debug_clone_eq() {
        let type_ref = TypeRef::Primitive(PrimitiveType::String);
        let cloned = type_ref.clone();
        assert_eq!(type_ref, cloned);
        assert!(format!("{:?}", type_ref).contains("Primitive"));
    }

    #[test]
    fn type_ref_primitive() {
        let type_ref = TypeRef::Primitive(PrimitiveType::Boolean);
        assert!(matches!(
            type_ref,
            TypeRef::Primitive(PrimitiveType::Boolean)
        ));
    }

    #[test]
    fn type_ref_array() {
        let inner = TypeRef::Primitive(PrimitiveType::String);
        let array = TypeRef::Array(Box::new(inner.clone()));
        if let TypeRef::Array(boxed) = array {
            assert_eq!(*boxed, inner);
        } else {
            panic!("Expected Array variant");
        }
    }

    #[test]
    fn type_ref_map() {
        let inner = TypeRef::Primitive(PrimitiveType::Integer);
        let map = TypeRef::Map(Box::new(inner.clone()));
        if let TypeRef::Map(boxed) = map {
            assert_eq!(*boxed, inner);
        } else {
            panic!("Expected Map variant");
        }
    }

    #[test]
    fn type_ref_named() {
        let named = TypeRef::Named("User".to_string());
        if let TypeRef::Named(name) = named {
            assert_eq!(name, "User");
        } else {
            panic!("Expected Named variant");
        }
    }

    #[test]
    fn type_ref_one_of() {
        let one_of = TypeRef::OneOf(vec![
            TypeRef::Named("Cat".to_string()),
            TypeRef::Named("Dog".to_string()),
        ]);
        if let TypeRef::OneOf(types) = one_of {
            assert_eq!(types.len(), 2);
        } else {
            panic!("Expected OneOf variant");
        }
    }

    #[test]
    fn type_ref_any_of() {
        let any_of = TypeRef::AnyOf(vec![
            TypeRef::Primitive(PrimitiveType::String),
            TypeRef::Primitive(PrimitiveType::Integer),
        ]);
        if let TypeRef::AnyOf(types) = any_of {
            assert_eq!(types.len(), 2);
        } else {
            panic!("Expected AnyOf variant");
        }
    }

    #[test]
    fn type_ref_all_of() {
        let all_of = TypeRef::AllOf(vec![TypeRef::Named("Base".to_string())]);
        if let TypeRef::AllOf(types) = all_of {
            assert_eq!(types.len(), 1);
        } else {
            panic!("Expected AllOf variant");
        }
    }

    #[test]
    fn type_ref_optional() {
        let inner = TypeRef::Primitive(PrimitiveType::String);
        let optional = TypeRef::Optional(Box::new(inner.clone()));
        if let TypeRef::Optional(boxed) = optional {
            assert_eq!(*boxed, inner);
        } else {
            panic!("Expected Optional variant");
        }
    }

    #[test]
    fn type_ref_unknown() {
        let unknown = TypeRef::Unknown;
        assert!(matches!(unknown, TypeRef::Unknown));
    }

    #[test]
    fn type_ref_nested() {
        let nested = TypeRef::Array(Box::new(TypeRef::Optional(Box::new(TypeRef::Named(
            "User".to_string(),
        )))));
        assert!(matches!(nested, TypeRef::Array(_)));
    }
}
