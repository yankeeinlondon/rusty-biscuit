#!/usr/bin/env python3
"""Generate synthetic 550-endpoint modules for the Q4 compile-time measurement.

synthetic_old.rs: today's shape (EndpointSpec { type Response; ENDPOINT_ID }).
synthetic_new.rs: the new Endpoint impl (Success, Failure, Decode, ENDPOINT_ID),
                  plus (feature synthetic-new-calls) one async method per
                  endpoint that instantiates the generic send.
Request/response structs and the erasing enum are identical in both.
"""
import sys, pathlib

N = int(sys.argv[1]) if len(sys.argv) > 1 else 550
out = pathlib.Path(__file__).resolve().parent.parent / "src"

def common(trait_impl):
    lines = [
        "//! GENERATED by scripts/gen_synthetic.py; do not edit.",
        "#![allow(dead_code, clippy::all)]",
        "use serde::{Deserialize, Serialize};",
        "use crate::api::{RequestBody, RequestParts};",
        "use crate::client::percent_encode as enc;",
        "",
    ]
    for i in range(N):
        lines += [
            "#[derive(Debug, Clone, Default, Serialize, Deserialize)]",
            f"pub struct Req{i} {{ pub owner: String, pub repo: String, pub id: String, pub page: Option<u32> }}",
            f"impl Req{i} {{",
            "    pub fn into_parts(self) -> Result<RequestParts, String> {",
            "        let mut query = vec![];",
            "        if let Some(p) = self.page { query.push((\"page\".to_string(), p.to_string())); }",
            f"        Ok(RequestParts {{ method: \"GET\", path: format!(\"/r/{{}}/{{}}/e{i}/{{}}\", enc(&self.owner), enc(&self.repo), enc(&self.id)), query, body: RequestBody::Empty, headers: vec![] }})",
            "    }",
            "}",
            "#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]",
            f"pub struct Resp{i} {{ pub id: u64, pub name: String, pub tags: Vec<String>, pub extra: Option<serde_json::Value> }}",
            trait_impl(i),
        ]
    lines.append("pub enum SynthRequest {")
    lines += [f"    E{i}(Req{i})," for i in range(N)]
    lines.append("}")
    for i in range(N):
        lines.append(f"impl From<Req{i}> for SynthRequest {{ fn from(r: Req{i}) -> Self {{ SynthRequest::E{i}(r) }} }}")
    lines.append("impl SynthRequest {")
    lines.append("    pub fn endpoint_id(&self) -> &'static str { match self {")
    lines += [f"        Self::E{i}(_) => \"E{i}\"," for i in range(N)]
    lines.append("    } }")
    lines.append("    pub fn into_parts(self) -> Result<RequestParts, String> { match self {")
    lines += [f"        Self::E{i}(r) => r.into_parts()," for i in range(N)]
    lines.append("    } }")
    lines.append("}")
    return lines

old = common(lambda i: "\n".join([
    f"impl EndpointSpec for Req{i} {{",
    f"    type Response = Resp{i};",
    f"    const ENDPOINT_ID: &'static str = \"E{i}\";",
    "}",
]))
old.insert(6, "pub trait EndpointSpec { type Response; const ENDPOINT_ID: &'static str; }")
(out / "synthetic_old.rs").write_text("\n".join(old) + "\n")

new = common(lambda i: "\n".join([
    f"impl crate::runtime::Endpoint for Req{i} {{",
    f"    type Success = Resp{i};",
    "    type Failure = SynthError;",
    f"    type Decode = crate::runtime::Json<Resp{i}>;",
    f"    const ENDPOINT_ID: &'static str = \"E{i}\";",
    "}",
]))
new.insert(6, "\n".join([
    "#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]",
    "pub struct SynthError { pub message: String }",
    "impl crate::runtime::ErrorBody for SynthError {",
    "    fn decode(body: &[u8]) -> Result<Self, crate::runtime::DecodeError> { crate::runtime::decode_json_error(body) }",
    "}",
    "impl crate::client::ErasedRequest for SynthRequest {",
    "    fn endpoint_id(&self) -> &'static str { SynthRequest::endpoint_id(self) }",
    "    fn into_parts(self) -> Result<RequestParts, String> { SynthRequest::into_parts(self) }",
    "}",
]))
new.append("#[cfg(feature = \"synthetic-new-calls\")]")
new.append("pub mod calls {")
new.append("    use super::*;")
new.append("    use crate::client::{CallOptions, DemoClient};")
new.append("    use crate::runtime::{Response, TransportError};")
for i in range(N):
    new.append(f"    pub async fn call_{i}(c: &DemoClient, r: Req{i}) -> Result<Response<Resp{i}, SynthError>, TransportError> {{ c.send_via::<SynthRequest, _>(r, CallOptions::default()).await }}")
new.append("}")
(out / "synthetic_new.rs").write_text("\n".join(new) + "\n")
print(f"wrote {N} endpoints")
