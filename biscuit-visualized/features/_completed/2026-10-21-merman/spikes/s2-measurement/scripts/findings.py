def main() -> None:
    spike = Path(sys.argv[sys.argv.index("--spike") + 1]) if "--spike" in sys.argv else Path(".")
    data = json.loads((spike / "results.json").read_text())
    values = {}
    runs, diagrams = None, None
    for host in ("macos", "linux"):
        sc = data["hosts"][host]["scorecard"]
        timing = sc.get("timing") or {}
        by = sc.get("timing_by_diagram") or {}
        raw_timing = data["hosts"][host].get("timing") or {}
        runs = raw_timing.get("runs", runs)
        for m, key in (("a", "a"), ("a-mw", "amw"), ("b", "b")):
            t = timing.get(m) or {}
            cold = t.get("cold_median_of_medians_ms")
            warm = t.get("warm_median_of_medians_ms")
            colds = sorted(v[m]["cold"] for v in by.values() if v.get(m, {}).get("cold"))
            p90 = colds[int(0.9 * (len(colds) - 1))] if colds else None
            diagrams = t.get("diagrams", diagrams)
            values[f"{host}_cold_{key}"] = f"{cold} ms ({p90:.1f})" if cold is not None and p90 is not None else "not run"
            values[f"{host}_cold_{key}_plain"] = f"{cold} ms" if cold is not None else "not run"
            values[f"{host}_warm_{key}"] = f"{warm} ms ({t.get('warm_max_median_ms')})" if warm is not None else "not run"
            values[f"{host}_warm_{key}_plain"] = f"{warm} ms" if warm is not None else "not run"
            rasters = [s["raster_ms"] for s in raw_timing.get("warm", []) if s["measurer"] == m and s["raster_ms"] == s["raster_ms"]]
            rasters.sort()
            values[f"{host}_raster_{key}"] = f"{rasters[len(rasters) // 2]:.1f} ms" if rasters else "not run"
    text = TEMPLATE.replace("RUNS", str(runs)).replace("DIAGRAMS", str(diagrams))
    for key, value in values.items():
        text = text.replace("{" + key + "}", value)
    (spike / "FINDINGS.md").write_text(text)
    print(f"wrote {spike / 'FINDINGS.md'}")


if __name__ == "__main__":
    main()
