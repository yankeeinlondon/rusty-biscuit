use super::*;

/// Writes `roster` as `<tmp>/claudine/docs/providers.yaml` and returns the
/// area, so the Darkmatter artifact path stays inside the temporary root.
fn fixture_area(root: &Path, roster: &str) -> PathBuf {
    let area = root.join("claudine");
    std::fs::create_dir_all(area.join("docs")).unwrap();
    std::fs::write(area.join("docs/providers.yaml"), roster).unwrap();
    area
}

const ROSTER: &str = r#"kind: sequence
list:
    - slug: claude
      cli_aliases: ["claude"]
      sniff_binding: Claude
    - slug: kimi
      cli_aliases: ["kimi", "kimicode", "kimi_code", "kimi-code"]
      sniff_binding: KimiCli
    - slug: paused
      skip_research: true
      sniff_binding: Goose
"#;

fn rows(area: &Path) -> Vec<(String, String, String)> {
    load_agentic_cli_names(area)
        .unwrap()
        .into_iter()
        .map(|row| (row.name, row.slug, row.binding))
        .collect()
}

fn row(name: &str, slug: &str, binding: &str) -> (String, String, String) {
    (name.into(), slug.into(), binding.into())
}

#[test]
fn names_are_slugs_then_aliases_deduplicated_and_skipped_entries_included() {
    let root = tempfile::tempdir().unwrap();
    let area = fixture_area(root.path(), ROSTER);
    assert_eq!(
        rows(&area),
        [
            row("claude", "claude", "Claude"),
            row("kimi", "kimi", "KimiCli"),
            row("kimicode", "kimi", "KimiCli"),
            row("kimi_code", "kimi", "KimiCli"),
            row("kimi-code", "kimi", "KimiCli"),
            row("paused", "paused", "Goose"),
        ]
    );
}

#[test]
fn emitted_artifact_is_deterministic_and_well_formed() {
    let root = tempfile::tempdir().unwrap();
    let area = fixture_area(root.path(), ROSTER);
    let first = build_agentic_clis(&area).unwrap();
    assert_eq!(first, build_agentic_clis(&area).unwrap());
    assert!(first.starts_with("// GENERATED by claudine-gen"));
    assert!(first.contains("    (\"kimi-code\", \"KimiCli\"),\n"));
    assert!(first.ends_with("];\n"));
}

#[test]
fn invalid_rosters_fail_loudly() {
    let cases = [
        ("unknown binding", ROSTER.replace("sniff_binding: Goose", "sniff_binding: NotACli"), "not a sniff `AiCli` variant"),
        ("missing binding", ROSTER.replace("      sniff_binding: Goose\n", ""), "has no string `sniff_binding`"),
        ("cross-entry collision", ROSTER.replace("[\"claude\"]", "[\"claude\", \"kimi_code\"]"), "claimed by both `claude` and `kimi`"),
        ("uppercase name", ROSTER.replace("\"kimicode\"", "\"KimiCode\""), "lowercase"),
        ("empty name", ROSTER.replace("\"kimicode\"", "\"\""), "lowercase"),
        ("missing slug", ROSTER.replace("    - slug: paused\n", "    - name: paused\n"), "no string `slug`"),
    ];
    for (label, roster, expected) in cases {
        let root = tempfile::tempdir().unwrap();
        let area = fixture_area(root.path(), &roster);
        let error = load_agentic_cli_names(&area).expect_err(label).to_string();
        assert!(error.contains(expected), "{label}: {error}");
    }
}

/// AC19: the check is clean against a freshly generated artifact and drifts
/// when a slug or alias is added, removed, or renamed, or a binding changes,
/// without regeneration.
#[test]
fn check_detects_every_roster_change_without_regeneration() {
    let root = tempfile::tempdir().unwrap();
    let area = fixture_area(root.path(), ROSTER);
    assert!(matches!(check_agentic_clis(&area).unwrap(), CheckOutcome::MissingCommitted { .. }));

    let path = agentic_clis_path(&area);
    assert!(path.starts_with(root.path()), "artifact must resolve under the monorepo root");
    std::fs::create_dir_all(path.parent().unwrap()).unwrap();
    std::fs::write(&path, build_agentic_clis(&area).unwrap()).unwrap();
    assert!(matches!(check_agentic_clis(&area).unwrap(), CheckOutcome::Clean));

    let edits = [
        ("added slug", ROSTER.replacen("list:\n", "list:\n    - slug: codex\n      sniff_binding: Codex\n", 1)),
        ("removed slug", ROSTER.replace("    - slug: paused\n      skip_research: true\n      sniff_binding: Goose\n", "")),
        ("added alias", ROSTER.replace("[\"claude\"]", "[\"claude\", \"claude_code\"]")),
        ("removed alias", ROSTER.replace(", \"kimi-code\"", "")),
        ("renamed alias", ROSTER.replace("\"kimicode\"", "\"kimi_cli\"")),
        ("renamed slug", ROSTER.replace("slug: paused", "slug: resumed")),
        ("changed binding", ROSTER.replace("sniff_binding: Goose", "sniff_binding: Pi")),
    ];
    for (label, roster) in edits {
        std::fs::write(area.join("docs/providers.yaml"), &roster).unwrap();
        assert!(
            matches!(check_agentic_clis(&area).unwrap(), CheckOutcome::Drift { .. }),
            "{label} must drift"
        );
    }
}
