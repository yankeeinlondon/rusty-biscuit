//! Families compilation stage: the unchained-ai artifact's family index →
//! the committed `lib/src/model_catalog/families_generated.rs` slice.
//!
//! Follows the signals generated-module precedent (single committed file,
//! full scope, its own check fn), but the compiled scope is data-driven:
//! the slice carries exactly the families reachable from a generated
//! expected-offering `catalog_id` (deduped across every provider), not the
//! artifact's full 260+ entry index — per-provider offering slices, not
//! the whole catalog (design/model-catalog-boundary.md, runtime
//! migration).
//!
//! A derived family key missing from the artifact's `families{}` is a loud
//! generation error: identity keys and the family index are produced by
//! the same unchained-ai builder, so a miss means the grammar and the
//! index disagree.
//!
//! Determinism contract: rows sort by family key (the lib binary-searches
//! them), member/rolling-alias lists keep artifact order, the file ends in
//! exactly one trailing newline, and the only stamp is the artifact's own
//! `generated_at` (the staleness anchor — copied, not clock-read).

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use claudine_catalog_types::family_key;
use serde_json::Value;

use crate::artifact::{self, ArtifactIndex};
use crate::emit::{indent, render_slice};
use crate::errors::GenError;
use crate::generate::{CheckOutcome, Generation, diff_lines};

/// The committed generated families path under an area root.
pub fn families_path(area: &Path) -> PathBuf {
    area.join("lib/src/model_catalog/families_generated.rs")
}

/// The deduped family-key set derived from every generation's
/// expected-offering `catalog_id`s (prefix rule), each mapped to one
/// representative catalog_id for error reporting.
pub fn compiled_family_keys(generations: &[Generation]) -> BTreeMap<String, String> {
    let mut keys = BTreeMap::new();
    for generation in generations {
        let Some(field) = generation
            .fields
            .iter()
            .find(|field| field.field == "expected_offerings")
        else {
            continue;
        };
        let Some(records) = field.value.as_array() else {
            continue;
        };
        for record in records {
            if let Some(catalog_id) = record.get("catalog_id").and_then(Value::as_str) {
                keys.entry(family_key(catalog_id).to_string())
                    .or_insert_with(|| catalog_id.to_string());
            }
        }
    }
    keys
}

/// Builds the deterministic `families_generated.rs` text for `area` from
/// one generation per provider (full roster scope).
pub fn build_families(area: &Path, generations: &[Generation]) -> Result<String, GenError> {
    let index = artifact::load(area)?;
    build_families_from(&index, generations)
}

/// Artifact-parameterized builder (the testable core of
/// [`build_families`]).
pub fn build_families_from(
    index: &ArtifactIndex,
    generations: &[Generation],
) -> Result<String, GenError> {
    let keys = compiled_family_keys(generations);
    let mut rows = Vec::with_capacity(keys.len());
    for (key, catalog_id) in &keys {
        let entry = index.family(key).ok_or_else(|| GenError::FamilyKeyMissing {
            key: key.clone(),
            catalog_id: catalog_id.clone(),
        })?;
        rows.push((key.as_str(), entry));
    }
    Ok(emit_file(&rows, index.generated_at()))
}

/// Byte-compares [`build_families`] output against the committed file —
/// the code path shared by the CLI `check` subcommand and the drift test.
pub fn check_families(area: &Path, generations: &[Generation]) -> Result<CheckOutcome, GenError> {
    let generated = build_families(area, generations)?;
    let path = families_path(area);
    if !path.is_file() {
        return Ok(CheckOutcome::MissingCommitted { path });
    }
    let committed = std::fs::read_to_string(&path).map_err(|source| GenError::Io {
        path: path.clone(),
        source,
    })?;
    if committed == generated {
        return Ok(CheckOutcome::Clean);
    }
    Ok(CheckOutcome::Drift {
        details: diff_lines(&committed, &generated),
    })
}

fn emit_file(rows: &[(&str, &artifact::FamilyEntry)], generated_at: &str) -> String {
    let mut out = String::from(
        "// GENERATED by claudine-gen — DO NOT EDIT BY HAND.\n\
         //\n\
         // Inputs:\n\
         //   ../unchained-ai/artifacts/models-catalog.json — the committed family index\n\
         //   expected-offering catalog_id joins across every provider — the key set\n\
         // Regenerate with `cargo run -p claudine-gen -- generate`; drift-check with\n\
         // `cargo run -p claudine-gen -- check` (the same code path as the drift test).\n\
         \n\
         //! Vendored family-index slice for `family_latest` resolution (generated).\n\n\
         use claudine_catalog_types::FamilyRow;\n\n\
         /// `generated_at` of the models-catalog artifact this slice was vendored\n\
         /// from — the staleness anchor for `family_latest` answers.\n",
    );
    out.push_str(&format!(
        "pub(super) const ARTIFACT_GENERATED_AT: &str = {generated_at:?};\n\n"
    ));
    out.push_str(
        "/// Every family reachable from a generated expected-offering\n\
         /// `catalog_id`, sorted by key (binary-searchable).\n\
         pub(super) static FAMILY_INDEX: &[FamilyRow] = &[\n",
    );
    for (key, entry) in rows {
        let inner = indent(2);
        out.push_str(&format!("{}FamilyRow {{\n", indent(1)));
        out.push_str(&format!("{inner}key: {key:?},\n"));
        let latest = match &entry.latest {
            Some(latest) => format!("Some({latest:?})"),
            None => "None".to_string(),
        };
        out.push_str(&format!("{inner}latest: {latest},\n"));
        out.push_str(&format!(
            "{inner}members: {},\n",
            render_slice(&quoted(&entry.members), 2)
        ));
        out.push_str(&format!(
            "{inner}rolling_aliases: {},\n",
            render_slice(&quoted(&entry.rolling_aliases), 2)
        ));
        out.push_str(&format!("{}}},\n", indent(1)));
    }
    out.push_str("];\n");
    out
}

fn quoted(items: &[String]) -> Vec<String> {
    items.iter().map(|item| format!("{item:?}")).collect()
}

#[cfg(test)]
mod tests {
    use std::collections::BTreeMap;
    use std::path::Path;

    use serde_json::json;

    use super::*;
    use crate::generate::{Provenance, ResolvedField};

    fn generation(slug: &str, offerings: Value) -> Generation {
        Generation {
            slug: slug.to_string(),
            fields: vec![ResolvedField {
                field: "expected_offerings",
                value: offerings,
                provenance: Provenance::Declared { kind: "research" },
            }],
            data_rs: String::new(),
            skips: Vec::new(),
            research: BTreeMap::new(),
            offering_join: Default::default(),
            artifact_warning: None,
        }
    }

    fn index(families: Value) -> ArtifactIndex {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("models-catalog.json");
        std::fs::write(
            &path,
            json!({
                "schema_version": crate::artifact::EXPECTED_SCHEMA_VERSION,
                "generated_at": "2026-07-01T00:00:00Z",
                "offerings": [],
                "families": families,
            })
            .to_string(),
        )
        .unwrap();
        crate::artifact::load_from(
            &path,
            chrono::DateTime::parse_from_rfc3339("2026-07-06T00:00:00Z")
                .unwrap()
                .with_timezone(&chrono::Utc),
        )
        .unwrap()
    }

    /// Keys dedupe across providers (claude and opencode both join
    /// `anthropic/claude-opus@*`) and unjoined records contribute
    /// nothing.
    #[test]
    fn compiled_keys_dedupe_across_providers_and_skip_unjoined() {
        let generations = [
            generation(
                "claude",
                json!([
                    { "id": "claude-opus-4-8", "catalog_id": "anthropic/claude-opus@4.8" },
                    { "id": "claude-sonnet-5", "catalog_id": "anthropic/claude-sonnet@5" },
                    { "id": "auto", "catalog_id": null },
                ]),
            ),
            generation(
                "opencode",
                json!([
                    { "id": "opencode/claude-opus-4-7", "catalog_id": "anthropic/claude-opus@4.7" },
                ]),
            ),
        ];
        let keys = compiled_family_keys(&generations);
        assert_eq!(
            keys.keys().collect::<Vec<_>>(),
            ["anthropic/claude-opus", "anthropic/claude-sonnet"]
        );
    }

    #[test]
    fn build_emits_sorted_binary_searchable_rows_with_the_artifact_stamp() {
        let index = index(json!({
            "anthropic/claude-opus": {
                "members": ["anthropic/claude-opus-4-7", "anthropic/claude-opus-4-8"],
                "latest": "anthropic/claude-opus@4.8",
                "rolling_aliases": ["openrouter/anthropic/claude-opus-latest"]
            },
            "anthropic/claude-sonnet": {
                "members": ["anthropic/claude-sonnet-5"]
            },
            "unreferenced/family": { "members": [] }
        }));
        let generations = [generation(
            "claude",
            json!([
                { "id": "claude-sonnet-5", "catalog_id": "anthropic/claude-sonnet@5" },
                { "id": "claude-opus-4-8", "catalog_id": "anthropic/claude-opus@4.8" },
            ]),
        )];
        let text = build_families_from(&index, &generations).unwrap();
        assert!(text.contains(
            "pub(super) const ARTIFACT_GENERATED_AT: &str = \"2026-07-01T00:00:00Z\";"
        ));
        // Sorted by key, only the referenced families.
        let opus = text.find("key: \"anthropic/claude-opus\",").expect("opus row");
        let sonnet = text
            .find("key: \"anthropic/claude-sonnet\",")
            .expect("sonnet row");
        assert!(opus < sonnet);
        assert!(!text.contains("unreferenced/family"));
        assert!(text.contains("latest: Some(\"anthropic/claude-opus@4.8\"),"));
        // Absent artifact fields emit their empty/None forms.
        assert!(text.contains("latest: None,"));
        assert!(text.contains("rolling_aliases: &[],"));
        assert!(text.ends_with("];\n") && !text.ends_with("\n\n"));
    }

    /// A derived key the artifact does not know is the
    /// grammar-vs-family-index disagreement and must fail loudly, naming
    /// both the key and the catalog_id it came from.
    #[test]
    fn missing_family_is_a_loud_generation_error() {
        let index = index(json!({}));
        let generations = [generation(
            "claude",
            json!([{ "id": "claude-opus-4-8", "catalog_id": "anthropic/claude-opus@4.8" }]),
        )];
        let err = build_families_from(&index, &generations).unwrap_err();
        match &err {
            GenError::FamilyKeyMissing { key, catalog_id } => {
                assert_eq!(key, "anthropic/claude-opus");
                assert_eq!(catalog_id, "anthropic/claude-opus@4.8");
            }
            other => panic!("expected FamilyKeyMissing, got: {other}"),
        }
    }

    /// Mirror of the signals drift check: clean when committed text
    /// matches, drift with a regen hint path otherwise, missing when the
    /// committed file is absent.
    #[test]
    fn check_families_reports_clean_drift_and_missing() {
        let dir = tempfile::tempdir().unwrap();
        let area = dir.path().join("claudine");
        std::fs::create_dir_all(area.join("lib/src/model_catalog")).unwrap();
        let artifact_dir = dir.path().join("unchained-ai/artifacts");
        std::fs::create_dir_all(&artifact_dir).unwrap();
        std::fs::write(
            artifact_dir.join("models-catalog.json"),
            json!({
                "schema_version": crate::artifact::EXPECTED_SCHEMA_VERSION,
                "generated_at": "2026-07-01T00:00:00Z",
                "offerings": [],
                "families": {
                    "anthropic/claude-opus": {
                        "members": ["anthropic/claude-opus-4-8"],
                        "latest": "anthropic/claude-opus@4.8"
                    }
                }
            })
            .to_string(),
        )
        .unwrap();
        let generations = [generation(
            "claude",
            json!([{ "id": "claude-opus-4-8", "catalog_id": "anthropic/claude-opus@4.8" }]),
        )];

        let missing = check_families(&area, &generations).unwrap();
        assert!(matches!(missing, CheckOutcome::MissingCommitted { .. }));

        let generated = build_families(&area, &generations).unwrap();
        std::fs::write(families_path(&area), &generated).unwrap();
        assert!(matches!(
            check_families(&area, &generations).unwrap(),
            CheckOutcome::Clean
        ));

        std::fs::write(families_path(&area), format!("{generated}// drift\n")).unwrap();
        assert!(matches!(
            check_families(&area, &generations).unwrap(),
            CheckOutcome::Drift { .. }
        ));
    }

    #[test]
    fn families_path_targets_the_model_catalog_module() {
        assert_eq!(
            families_path(Path::new("/area")),
            Path::new("/area/lib/src/model_catalog/families_generated.rs")
        );
    }
}
