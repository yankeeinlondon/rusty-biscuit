//! The committed `docs/providers/catalog.json` superset projection.
//!
//! Compiled-subset mechanics (design/catalog-generation.md): the runtime
//! binary embeds only `data.rs`; gen additionally emits this committed
//! JSON document carrying the FULL research projection for every provider
//! — resolved catalog values with per-field provenance plus every
//! validated topic frontmatter (mapped and unmapped fields). Tooling reads
//! it from the repo when present; the claudine lib never reads it at
//! runtime.
//!
//! Determinism contract: every JSON object is emitted with alphabetically
//! sorted keys (so output is byte-identical whether or not serde_json's
//! `preserve_order` feature is unified in), arrays keep document order,
//! the file ends in exactly one trailing newline, and nothing is
//! timestamped.

use std::path::{Path, PathBuf};

use serde_json::{Map, Value};

use crate::generate::{CheckOutcome, Generation, Provenance, diff_lines};
use crate::registry::{DeclaredSource, entry_for};

/// Version stamp for the catalog document shape. Bump when the structure
/// documented in `$doc` changes.
pub const CATALOG_SCHEMA_VERSION: u64 = 3;

/// Shape documentation embedded in the emitted document itself.
const CATALOG_DOC: &str = "GENERATED by `claudine-gen generate` — do not hand-edit. Verified by \
     `claudine-gen check` and the gen drift test. Shape: providers.<slug>.catalog.<field> = \
     { value, source: { kind: roster|facts|research, key | topic+path }, override?: { reason, \
     stale, suppressed } } (resolved catalog values with per-field provenance); \
     providers.<slug>.research.<topic> = the schema-validated topic frontmatter, mapped AND \
     unmapped fields. The claudine lib never reads this file at runtime.";

/// The committed catalog path under an area root.
pub fn catalog_path(area: &Path) -> PathBuf {
    area.join("docs/providers/catalog.json")
}

/// Builds the deterministic catalog document text from one generation per
/// provider (any order — providers are keyed and sorted by slug).
pub fn build_catalog(generations: &[Generation]) -> String {
    let mut providers = Map::new();
    let mut sorted: Vec<&Generation> = generations.iter().collect();
    sorted.sort_by(|a, b| a.slug.cmp(&b.slug));
    for generation in sorted {
        providers.insert(generation.slug.clone(), provider_entry(generation));
    }

    // Alphabetical insertion order ($doc < providers < schema_version)
    // keeps the output stable under both serde_json map backends.
    let mut root = Map::new();
    root.insert("$doc".into(), Value::String(CATALOG_DOC.into()));
    root.insert("providers".into(), Value::Object(providers));
    root.insert(
        "schema_version".into(),
        Value::Number(CATALOG_SCHEMA_VERSION.into()),
    );

    let mut text = serde_json::to_string_pretty(&Value::Object(root))
        .expect("catalog document is always serializable");
    text.push('\n');
    text
}

/// Byte-compares [`build_catalog`] output against the committed file —
/// the same code path behind the CLI `check` subcommand and the drift
/// test. `generations` must cover every provider (the caller generates
/// the full roster scope; a partial set would emit a partial catalog).
pub fn check_catalog(area: &Path, generations: &[Generation]) -> Result<CheckOutcome, crate::GenError> {
    let path = catalog_path(area);
    let generated = build_catalog(generations);
    if !path.is_file() {
        return Ok(CheckOutcome::MissingCommitted { path });
    }
    let committed = std::fs::read_to_string(&path).map_err(|source| crate::GenError::Io {
        path: path.clone(),
        source,
    })?;
    if committed == generated {
        return Ok(CheckOutcome::Clean);
    }
    Ok(CheckOutcome::Drift {
        details: diff_lines(&committed, &generated),
    })
}

/// One provider's `{ catalog, research }` entry.
fn provider_entry(generation: &Generation) -> Value {
    let mut catalog = Map::new();
    let mut fields: Vec<_> = generation.fields.iter().collect();
    fields.sort_by_key(|f| f.field);
    for field in fields {
        let mut record = Map::new();
        if let Provenance::Override {
            reason,
            suppressed,
            stale,
        } = &field.provenance
        {
            let mut over = Map::new();
            over.insert("reason".into(), Value::String(reason.clone()));
            over.insert("stale".into(), Value::Bool(*stale));
            over.insert(
                "suppressed".into(),
                suppressed.as_ref().map(deep_sorted).unwrap_or(Value::Null),
            );
            record.insert("override".into(), Value::Object(over));
        }
        let source = entry_for(field.field)
            .map(|entry| source_json(&entry.source))
            .unwrap_or(Value::Null);
        record.insert("source".into(), source);
        record.insert("value".into(), deep_sorted(&field.value));
        catalog.insert(field.field.to_string(), Value::Object(record));
    }

    let mut research = Map::new();
    for (topic, frontmatter) in &generation.research {
        research.insert(topic.clone(), deep_sorted(frontmatter));
    }

    let mut entry = Map::new();
    entry.insert("catalog".into(), Value::Object(catalog));
    entry.insert("research".into(), Value::Object(research));
    Value::Object(entry)
}

/// Declared-source JSON with alphabetically inserted keys.
fn source_json(source: &DeclaredSource) -> Value {
    let mut map = Map::new();
    match source {
        DeclaredSource::Roster { key } => {
            map.insert("key".into(), Value::String((*key).into()));
            map.insert("kind".into(), Value::String("roster".into()));
        }
        DeclaredSource::Facts { key } => {
            map.insert("key".into(), Value::String((*key).into()));
            map.insert("kind".into(), Value::String("facts".into()));
        }
        DeclaredSource::Research { topic, path } => {
            map.insert("kind".into(), Value::String("research".into()));
            map.insert("path".into(), Value::String((*path).into()));
            map.insert("topic".into(), Value::String((*topic).into()));
        }
    }
    Value::Object(map)
}

/// Recursively rebuilds objects with alphabetically sorted key insertion;
/// arrays keep document order.
fn deep_sorted(value: &Value) -> Value {
    match value {
        Value::Object(map) => {
            let mut pairs: Vec<(&String, &Value)> = map.iter().collect();
            pairs.sort_by_key(|(k, _)| k.as_str());
            let mut sorted = Map::new();
            for (key, value) in pairs {
                sorted.insert(key.clone(), deep_sorted(value));
            }
            Value::Object(sorted)
        }
        Value::Array(items) => Value::Array(items.iter().map(deep_sorted).collect()),
        other => other.clone(),
    }
}

#[cfg(test)]
mod tests {
    use std::collections::BTreeMap;

    use serde_json::json;

    use super::*;
    use crate::generate::ResolvedField;

    fn generation(slug: &str) -> Generation {
        Generation {
            slug: slug.to_string(),
            fields: vec![
                ResolvedField {
                    field: "slug",
                    value: json!(slug),
                    provenance: Provenance::Declared { kind: "roster" },
                },
                ResolvedField {
                    field: "model_env_vars",
                    value: json!(["B_VAR", "A_VAR"]),
                    provenance: Provenance::Override {
                        reason: "pin order".into(),
                        suppressed: Some(json!(["A_VAR"])),
                        stale: false,
                    },
                },
            ],
            data_rs: String::new(),
            skips: Vec::new(),
            research: BTreeMap::from([(
                "skills".to_string(),
                json!({ "zeta": 1, "alpha": { "b": 2, "a": 1 } }),
            )]),
            offering_join: Default::default(),
            artifact_warning: None,
        }
    }

    #[test]
    fn catalog_sorts_providers_fields_and_nested_keys() {
        let text = build_catalog(&[generation("codex"), generation("claude")]);
        let value: Value = serde_json::from_str(&text).unwrap();
        let providers: Vec<&String> = value["providers"].as_object().unwrap().keys().collect();
        assert_eq!(providers, ["claude", "codex"]);
        // Catalog fields alphabetical, not registry order.
        let fields: Vec<&String> = value["providers"]["claude"]["catalog"]
            .as_object()
            .unwrap()
            .keys()
            .collect();
        assert_eq!(fields, ["model_env_vars", "slug"]);
        // Nested research objects deep-sorted; arrays untouched.
        let research = &value["providers"]["claude"]["research"]["skills"];
        let keys: Vec<&String> = research.as_object().unwrap().keys().collect();
        assert_eq!(keys, ["alpha", "zeta"]);
        assert_eq!(
            value["providers"]["claude"]["catalog"]["model_env_vars"]["value"],
            json!(["B_VAR", "A_VAR"])
        );
        assert!(text.ends_with("}\n") && !text.ends_with("\n\n"));
    }

    #[test]
    fn catalog_carries_provenance_and_override_records() {
        let text = build_catalog(&[generation("claude")]);
        let value: Value = serde_json::from_str(&text).unwrap();
        let catalog = &value["providers"]["claude"]["catalog"];
        assert_eq!(catalog["slug"]["source"]["kind"], "roster");
        assert_eq!(catalog["slug"]["source"]["key"], "slug");
        assert!(catalog["slug"].get("override").is_none());
        let over = &catalog["model_env_vars"]["override"];
        assert_eq!(over["reason"], "pin order");
        assert_eq!(over["stale"], false);
        assert_eq!(over["suppressed"], json!(["A_VAR"]));
    }

    #[test]
    fn build_catalog_is_deterministic() {
        let a = build_catalog(&[generation("claude"), generation("codex")]);
        let b = build_catalog(&[generation("codex"), generation("claude")]);
        assert_eq!(a, b);
    }
}
