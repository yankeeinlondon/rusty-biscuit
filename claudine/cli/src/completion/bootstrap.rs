//! Shell completion script rendering for `claudine completions <shell>`.
//!
//! Bash, zsh, fish, PowerShell, and Elvish are served by shell-specific
//! scripts that shell out to the hidden `claudine __complete` subcommand on
//! every `<TAB>`. Routing inside `__complete` flows through
//! [`super::engine::run`], which classifies the cursor slot (root menu,
//! composition positional, setter value) and dispatches to a slot-specific
//! completer.
//!
//! ## Installation
//!
//! Bash:
//!
//! ```sh
//! claudine completions bash > ~/.local/share/bash-completion/completions/claudine
//! ```
//!
//! Zsh:
//!
//! ```sh
//! claudine completions zsh > "${fpath[1]}/_claudine"
//! ```
//!
//! Fish:
//!
//! ```sh
//! claudine completions fish > ~/.config/fish/completions/claudine.fish
//! ```
//!
//! PowerShell (in `$PROFILE`):
//!
//! ```powershell
//! claudine completions powershell | Out-String | Invoke-Expression
//! ```
//!
//! Elvish (a module, then `use claudine-completion` in `rc.elv`):
//!
//! ```sh
//! claudine completions elvish > ~/.config/elvish/lib/claudine-completion.elv
//! ```
//!
//! The scripts work the same way on every shell: on each `<TAB>`, the
//! registered callback invokes `claudine __complete --current <INDEX> --
//! <argv>`. The engine classifies the cursor position, applies the
//! slot-specific rules, and prints one candidate per line on stdout. The
//! shell then presents those candidates to the user. When `__complete`
//! returns no candidates, the shell script falls back to its default file
//! completion so non-targeted argument positions still behave as if
//! completion were unset.

use clap_complete::Shell;

/// Render the completion script for `shell`.
///
/// Returned string includes a trailing newline so it prints cleanly as a
/// CLI subcommand output. Redirect the output into the shell's completion
/// file; the scripts are idempotent on reload.
pub(crate) fn render(shell: Shell) -> String {
    match shell {
        Shell::Bash => BASH_SCRIPT.to_string(),
        Shell::Zsh => ZSH_SCRIPT.to_string(),
        Shell::Fish => FISH_SCRIPT.to_string(),
        Shell::PowerShell => POWERSHELL_SCRIPT.to_string(),
        Shell::Elvish => ELVISH_SCRIPT.to_string(),
        // `clap_complete::Shell` is `#[non_exhaustive]`; any future shell
        // that clap adds falls back to the bash-style script. That is the
        // closest documented shape for POSIX-like shells.
        _ => BASH_SCRIPT.to_string(),
    }
}

/// Bash completion script.
///
/// Registers `_claudine_complete` as the completion function for the
/// `claudine` command. On every `<TAB>`, the function shells out to
/// `claudine __complete --current $COMP_CWORD -- "${COMP_WORDS[@]}"` and
/// treats each line of stdout as a candidate. If the call fails or returns
/// no candidates, bash falls back to default file completion (`bashdefault`
/// + `default`).
///
/// `-o nosort` preserves the order the engine emits (currently alphabetical
/// from a `BTreeSet`, but the contract reserves the right to change this).
/// The `-o nospace` option is intentionally NOT set: bash's default trailing
/// space after a unique match is correct for every engine candidate (files,
/// not directories).
///
/// Setting `CLAUDINE_COMPLETION_DEBUG=1` in the user's shell environment
/// exposes engine stderr at the next `<TAB>` press; without it, stderr is
/// swallowed so transient panics do not corrupt the user's prompt. This is
/// an operational-visibility flag, not a feature flag — the completion
/// engine itself ignores the variable.
const BASH_SCRIPT: &str = r#"# Claudine shell completions (bash)
# Generated by `claudine completions bash`.
#
# The `__complete` subcommand is the Claudine completion engine. It
# classifies the cursor position and prints one candidate per line on
# stdout. When it has no candidates (non-targeted positions, errors) the
# script lets bash fall back to its default file completion.
#
# Set CLAUDINE_COMPLETION_DEBUG=1 to surface engine stderr at the next
# <TAB> press; the default swallows stderr so transient engine panics do
# not corrupt the user's prompt.

_claudine_complete() {
    local IFS=$'\n'
    local candidates
    if [ -n "${CLAUDINE_COMPLETION_DEBUG:-}" ]; then
        candidates=( $(command claudine __complete --current "$COMP_CWORD" -- "${COMP_WORDS[@]}") )
    else
        candidates=( $(command claudine __complete --current "$COMP_CWORD" -- "${COMP_WORDS[@]}" 2>/dev/null) )
    fi
    if [ ${#candidates[@]} -gt 0 ] && [ -n "${candidates[0]}" ]; then
        COMPREPLY=( "${candidates[@]}" )
        return 0
    fi
    COMPREPLY=()
    return 0
}

complete -o nosort -o bashdefault -o default -F _claudine_complete claudine
"#;

/// Zsh completion script.
///
/// Uses the `#compdef claudine` directive so the file can be dropped under
/// any directory in `$fpath` and be autoloaded. The main function splits
/// `__complete`'s stdout on newlines (`(@f)` flag), then feeds the resulting
/// array to `compadd`. When the engine emits nothing, the script falls back
/// to `_files` for default file completion.
///
/// When sourced directly (e.g. `source <(claudine completions zsh)`) before
/// `compinit` has run, `compdef` is not yet defined. The guard at the bottom
/// autoloads and initializes `compinit` on demand so `compdef _claudine
/// claudine` always registers, regardless of rc-file ordering.
///
/// Setting `CLAUDINE_COMPLETION_DEBUG=1` in the user's shell environment
/// exposes engine stderr at the next `<TAB>` press; without it, stderr is
/// swallowed so transient panics do not corrupt the user's prompt. This is
/// an operational-visibility flag, not a feature flag — the completion
/// engine itself ignores the variable.
const ZSH_SCRIPT: &str = r#"#compdef claudine
# Claudine shell completions (zsh)
# Generated by `claudine completions zsh`.
#
# The `__complete` subcommand is the Claudine completion engine. It
# classifies the cursor position and prints one candidate per line on
# stdout. When it has no candidates (non-targeted positions, errors) the
# function falls back to `_files` so default file completion still fires.
#
# Set CLAUDINE_COMPLETION_DEBUG=1 to surface engine stderr at the next
# <TAB> press; the default swallows stderr so transient engine panics do
# not corrupt the user's prompt.

_claudine() {
    local -a candidates
    local current=$((CURRENT - 1))
    if [ -n "${CLAUDINE_COMPLETION_DEBUG:-}" ]; then
        candidates=("${(@f)$(command claudine __complete --current $current -- "${words[@]}")}")
    else
        candidates=("${(@f)$(command claudine __complete --current $current -- "${words[@]}" 2>/dev/null)}")
    fi
    if (( ${#candidates[@]} > 0 )) && [[ -n "${candidates[1]}" ]]; then
        # Engine candidates may be fuzzy/substring matches, so they often
        # share no common prefix with what the user typed. Without the
        # guards below, zsh computes an empty unambiguous prefix and
        # silently erases the typed text.
        #
        # - `-U` suppresses compadd's default prefix-match filter so the
        #   candidates survive at all.
        # - `-Q` skips quoting of special characters (paths are already in
        #   their final shell form).
        # - `compstate[insert]=menu` forces menu-completion mode so the
        #   engine's substring matches are presented as choices instead of
        #   being collapsed into a non-existent common prefix.
        # - `-S ''` suppresses the trailing space compadd appends after a
        #   unique match; path candidates already have their terminator.
        compstate[insert]=menu
        compadd -U -Q -S '' -- "${candidates[@]}"
        return 0
    fi
    _files
}

# When this script is sourced before `compinit` has run, `compdef` is not
# yet defined. Autoload and initialize the completion system on demand so
# the registration below always succeeds.
if ! (( $+functions[compdef] )); then
    autoload -Uz compinit
    compinit -u 2>/dev/null
fi
compdef _claudine claudine
"#;

/// Fish completion script.
///
/// Fish's completion model merges every `complete -c claudine ...` command
/// into one candidate set, so the script registers a single completion that
/// delegates entirely to `__complete`. The `-f` registration keeps fish from
/// mixing default file candidates into curated Claudine-owned slots; when the
/// engine returns nothing, the function explicitly calls
/// `__fish_complete_path` so non-targeted positions still get native file
/// completion.
///
/// Setting `CLAUDINE_COMPLETION_DEBUG=1` in the user's shell environment
/// exposes engine stderr at the next `<TAB>` press; without it, stderr is
/// swallowed so transient panics do not corrupt the user's prompt. This is
/// an operational-visibility flag, not a feature flag — the completion
/// engine itself ignores the variable.
const FISH_SCRIPT: &str = r#"# Claudine shell completions (fish)
# Generated by `claudine completions fish`.
#
# The `__complete` subcommand is the Claudine completion engine. It
# classifies the cursor position and prints one candidate per line on
# stdout. When it has no candidates (non-targeted positions, errors) this
# function falls back to fish's path completer.
#
# Set CLAUDINE_COMPLETION_DEBUG=1 to surface engine stderr at the next
# <TAB> press; the default swallows stderr so transient engine panics do
# not corrupt the user's prompt.

function __claudine_complete
    set -l tokens (commandline -opc)
    set -l current_partial (commandline -ct)
    set -l argv_all claudine $tokens[2..] $current_partial
    set -l idx (math (count $argv_all) - 1)
    set -l candidates
    if set -q CLAUDINE_COMPLETION_DEBUG
        set candidates (command claudine __complete --current $idx -- $argv_all)
    else
        set candidates (command claudine __complete --current $idx -- $argv_all 2>/dev/null)
    end
    if test (count $candidates) -gt 0
        printf '%s\n' $candidates
    else
        __fish_complete_path $current_partial
    end
end

complete -c claudine -f -a '(__claudine_complete)'
"#;

/// PowerShell completion script.
///
/// Registers a native argument completer for `claudine` that rebuilds argv
/// from the command AST (words that end before the cursor, plus the word
/// under it) and hands it to `claudine __complete`. PowerShell does not
/// filter a completer's results by prefix, so the engine's fuzzy matches
/// survive; an empty result lets PowerShell fall back to path completion.
///
/// `Register-ClaudineShortcutCompletion` attaches the same completer to a
/// user shortcut such as `function compose { claudine compose @args }`; the
/// `-Prefix` words stand in for the subcommand the shortcut supplies, so the
/// engine sees the line as `claudine compose …`.
///
/// Every engine argument travels in one splatted array: PowerShell would
/// otherwise reinterpret a bare `--`. Windows PowerShell 5.1 drops an empty
/// native argument, which is harmless because the engine treats a cursor
/// index one past the end of argv as an empty partial.
///
/// Setting `CLAUDINE_COMPLETION_DEBUG=1` surfaces engine stderr, matching the
/// other scripts.
const POWERSHELL_SCRIPT: &str = r#"# Claudine shell completions (PowerShell)
# Generated by `claudine completions powershell`.
#
# The `__complete` subcommand is the Claudine completion engine. It
# classifies the cursor position and prints one candidate per line on
# stdout. When it has no candidates (non-targeted positions, errors) the
# completer returns nothing and PowerShell falls back to path completion.
#
# Shortcut functions get the same completion through
# Register-ClaudineShortcutCompletion:
#
#   function compose { claudine compose @args }
#   Register-ClaudineShortcutCompletion -Name compose -Prefix compose
#
# Set $env:CLAUDINE_COMPLETION_DEBUG = 1 to surface engine stderr at the
# next <TAB> press; the default swallows stderr so transient engine panics
# do not corrupt the prompt.

function __ClaudineComplete {
    param(
        [string]$WordToComplete,
        $CommandAst,
        [int]$CursorPosition,
        [string[]]$Prefix
    )

    $claudine = Get-Command -Name claudine -CommandType Application -ErrorAction SilentlyContinue |
        Select-Object -First 1
    if (-not $claudine) { return }

    $argv = [System.Collections.Generic.List[string]]::new()
    $argv.Add('claudine')
    foreach ($word in $Prefix) { $argv.Add($word) }
    $elements = $CommandAst.CommandElements
    for ($i = 1; $i -lt $elements.Count; $i++) {
        $element = $elements[$i]
        if ($element.Extent.EndOffset -ge $CursorPosition) { break }
        if ($element -is [System.Management.Automation.Language.StringConstantExpressionAst]) {
            $argv.Add($element.Value)
        } else {
            $argv.Add($element.Extent.Text)
        }
    }
    $argv.Add(($WordToComplete -replace '^[''"]|[''"]$', ''))

    $engineArgs = @('__complete', '--current', ($argv.Count - 1), '--') + $argv.ToArray()
    if ($env:CLAUDINE_COMPLETION_DEBUG) {
        $candidates = & $claudine.Source @engineArgs
    } else {
        $candidates = & $claudine.Source @engineArgs 2>$null
    }

    foreach ($candidate in $candidates) {
        if ([string]::IsNullOrEmpty($candidate)) { continue }
        $completion = $candidate
        if ($candidate -match '[\s''"`$;|&(){}<>,]' -or $candidate -match '^[@#]') {
            $completion = "'" + ($candidate -replace "'", "''") + "'"
        }
        $type = if ($candidate.StartsWith('-')) { 'ParameterName' } else { 'ParameterValue' }
        [System.Management.Automation.CompletionResult]::new($completion, $candidate, $type, $candidate)
    }
}

function Register-ClaudineShortcutCompletion {
    param(
        [Parameter(Mandatory)][string]$Name,
        [Parameter(Mandatory)][string[]]$Prefix
    )
    Register-ArgumentCompleter -Native -CommandName $Name -ScriptBlock {
        param($wordToComplete, $commandAst, $cursorPosition)
        __ClaudineComplete $wordToComplete $commandAst $cursorPosition $Prefix
    }.GetNewClosure()
}

Register-ArgumentCompleter -Native -CommandName 'claudine', 'claudine.exe' -ScriptBlock {
    param($wordToComplete, $commandAst, $cursorPosition)
    __ClaudineComplete $wordToComplete $commandAst $cursorPosition @()
}
"#;

/// Elvish completion script.
///
/// Loaded as a module (`use claudine-completion`) so `shortcut` stays
/// callable from `rc.elv`; the arg-completer for `claudine` also works when
/// the script is merely `eval`'d. When the engine returns nothing the
/// completer falls back to `edit:complete-filename`.
///
/// Elvish filters every argument candidate through
/// `edit:completion:matcher`, a prefix match by default, which would discard
/// the engine's fuzzy matches (`slow` → `prompts/slow.md`). The script wraps
/// the `argument` matcher: it passes everything through for the completion
/// the engine just answered and defers to the previously installed matcher
/// (or `edit:match-prefix`) for every other completion.
///
/// Setting `CLAUDINE_COMPLETION_DEBUG=1` surfaces engine stderr, matching the
/// other scripts.
const ELVISH_SCRIPT: &str = r#"# Claudine shell completions (elvish)
# Generated by `claudine completions elvish`.
#
# Install as a module and load it from rc.elv:
#
#   claudine completions elvish > ~/.config/elvish/lib/claudine-completion.elv
#   use claudine-completion
#
# Shortcut functions get the same completion through `shortcut`:
#
#   fn compose {|@a| claudine compose $@a }
#   claudine-completion:shortcut compose compose
#
# The `__complete` subcommand is the Claudine completion engine. It
# classifies the cursor position and prints one candidate per line on
# stdout. When it has no candidates (non-targeted positions, errors) the
# completer falls back to filename completion.
#
# Set CLAUDINE_COMPLETION_DEBUG=1 to surface engine stderr at the next
# <TAB> press; the default swallows stderr so transient engine panics do
# not corrupt the prompt.

use os

# The engine has already matched (fuzzily) against the typed word, so its
# candidates must not be prefix-filtered again by Elvish's matcher. Every
# other completion keeps the matcher that was installed before this one.
var engine-matched = $false
var fallback-matcher = $edit:match-prefix~
if (has-key $edit:completion:matcher argument) {
    set fallback-matcher = $edit:completion:matcher[argument]
} elif (has-key $edit:completion:matcher '') {
    set fallback-matcher = $edit:completion:matcher['']
}
set edit:completion:matcher[argument] = {|seed|
    if $engine-matched {
        set engine-matched = $false
        each {|_| put $true }
    } else {
        $fallback-matcher $seed
    }
}

fn complete {|prefix words|
    # `$@words[1..]` would slice each word rather than the list.
    var typed = $words[1..]
    var argv = [claudine $@prefix $@typed]
    var current = (- (count $argv) 1)
    var candidates = []
    try {
        if (has-env CLAUDINE_COMPLETION_DEBUG) {
            set candidates = [(e:claudine __complete --current $current -- $@argv | from-lines)]
        } else {
            set candidates = [(e:claudine __complete --current $current -- $@argv 2>$os:dev-null | from-lines)]
        }
    } catch {
        set candidates = []
    }
    if (> (count $candidates) 0) {
        set engine-matched = $true
        put $@candidates
    } else {
        edit:complete-filename $words[-1]
    }
}

fn shortcut {|name @prefix|
    set edit:completion:arg-completer[$name] = {|@words| complete $prefix $words }
}

set edit:completion:arg-completer[claudine] = {|@words| complete [] $words }
"#;

