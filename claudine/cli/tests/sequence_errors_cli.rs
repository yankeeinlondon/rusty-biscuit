#[test]
fn a_reference_cycle_reports_every_hop() {
    let workspace = tempdir().unwrap();
    write(&workspace, "a.yaml", "kind: task\ntask: b.yaml\n");
    write(&workspace, "b.yaml", "kind: task\ntask: a.yaml\n");
    let doc = write(
        &workspace,
        "seq.md",
        "---\nsequence:\n  - name: one\n    task: a.yaml\n---\nBody.\n",
    );

    let stderr = run_and_flatten(&workspace, &doc, &[]);
    assert!(stderr.contains("reference cycle"), "stderr:\n{stderr}");
    // Counting arrows rather than matching paths: long absolute paths are
    // hyphen-wrapped by the renderer, which would split a path substring.
    assert_eq!(
        stderr.matches('\u{2192}').count(),
        3,
        "the chain must name every hop (entry → a → b → a); stderr:\n{stderr}"
    );
}

