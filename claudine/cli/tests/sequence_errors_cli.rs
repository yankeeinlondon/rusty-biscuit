//! Acceptance-criteria error coverage for `claudine sequence`, end to end.
//!
//! Every case here is rejected *before* a provider is launched, so none of them
//! needs a provider stub on `PATH`. That is what makes this binary
//! cross-platform: the sibling sequence binaries gate on `unix` only because a
//! `#!/bin/sh` fake provider cannot exist on Windows, and no test below needs
//! one.
//!
//! Sibling coverage that is deliberately not duplicated here: reference cycles,
//! nested sequences, direct group execution, group `loop`, write-back
//! collisions, late-binding shell, and static empty lists all live in
//! `sequence_cli.rs`; reserved-key *writes* (the `set` side effect) live in
//! `composition_outputs.rs`.

use std::fs;
use std::path::Path;
use tempfile::{TempDir, tempdir};
mod common;
use common::strip_ansi;

/// Run `claudine sequence --dry-run` against `file` and return flattened stderr.
///
/// Errors render through `Prose`, which wraps to the terminal width and
/// prefixes continuation lines. Flattening to single-spaced text lets an
/// assertion name the message rather than the wrap points, which are a
/// function of the host's width and would make these tests width-sensitive.
fn run_and_flatten(workspace: &TempDir, file: &Path, extra_args: &[&str]) -> String {
    let mut args: Vec<&str> = vec!["sequence", "--dry-run"];
    args.extend_from_slice(extra_args);
    let file_arg = file.to_str().unwrap();
    args.push(file_arg);

    let output = assert_cmd::Command::cargo_bin("claudine").unwrap()
        .env("NO_COLOR", "1")
        .env("HOME", workspace.path())
        .current_dir(workspace.path())
        .args(&args)
        .assert()
        .failure()
        .get_output()
        .clone();

    flatten(&strip_ansi(&String::from_utf8_lossy(&output.stderr)))
}

/// Collapse block-quote prefixes and wrapped whitespace into one line.
fn flatten(text: &str) -> String {
    text.replace('\u{2503}', " ")
        .split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
}

/// Write `body` as `<workspace>/<name>` and return its path.
fn write(workspace: &TempDir, name: &str, body: &str) -> std::path::PathBuf {
    let path = workspace.path().join(name);
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent).unwrap();
    }
    fs::write(&path, body).unwrap();
    path
}

/// Write a Markdown sequence document whose `sequence:` value is `source`.
fn source_doc(workspace: &TempDir, name: &str, source: &str) -> std::path::PathBuf {
    write(
        workspace,
        name,
        &format!("---\nsequence: \"{source}\"\n---\nStep {{{{ state.name }}}}.\n"),
    )
}

