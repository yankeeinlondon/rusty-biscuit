use std::fs;
use std::path::{Path, PathBuf};

use serde_json::{Value, json};

use crate::error::Result;
use crate::events::{AgenticEvent, HookerConfig, Provider};

use super::atomic::atomic_write;
use super::backup::create_backup;
use super::trait_def::{AgentConfigurator, RegistrationResult, SkipReason};

/// Plugin name registered in opencode.json.
const PLUGIN_NAME: &str = "claudine-bridge";

/// TypeScript bridge template for the Claudine OpenCode plugin.
///
/// Placeholder `{{EVENT_HANDLERS}}` is replaced with per-event handler code.
const BRIDGE_TEMPLATE: &str = r#"// Claudine bridge plugin for OpenCode
// Auto-generated by claudine — do not edit manually

import { execSync } from "child_process";

interface OpenCodePlugin {
  name: string;
  onEvent(event: string, data: unknown): void;
}

const EVENT_MAP: Record<string, string> = {
{{EVENT_MAP_ENTRIES}}
};

const plugin: OpenCodePlugin = {
  name: "claudine-bridge",
  onEvent(event: string, data: unknown) {
    const mapped = EVENT_MAP[event];
    if (mapped) {
      try {
        const payload = JSON.stringify(data ?? {});
        execSync(`claudine handle ${mapped} '${payload}'`, {
          timeout: 30000,
          stdio: "ignore",
        });
      } catch {
        // Silently ignore errors to avoid disrupting OpenCode
      }
    }
  },
};

export default plugin;
"#;

pub(crate) struct OpenCodeConfigurator;

impl AgentConfigurator for OpenCodeConfigurator {
    fn provider(&self) -> Provider {
        Provider::OpenCode
    }

    fn register(
        &self,
        config: &HookerConfig,
        config_dir: Option<&Path>,
    ) -> Result<RegistrationResult> {
        let opencode_path = config_path(config_dir);
        if !opencode_path.exists() {
            return Ok(RegistrationResult::Skipped(SkipReason::NotDetected));
        }

        if self.is_registered(config_dir)? {
            return Ok(RegistrationResult::Skipped(SkipReason::AlreadyRegistered));
        }

        create_backup(&opencode_path, Provider::OpenCode)?;

        // Generate the bridge plugin TypeScript file
        let plugin_path = plugin_dir(config_dir).join("claudine-bridge.ts");
        let bridge_source = generate_bridge(config);
        if let Some(parent) = plugin_path.parent() {
            fs::create_dir_all(parent)?;
        }
        atomic_write(&plugin_path, bridge_source.as_bytes())?;

        // Register plugin in opencode.json
        let content = fs::read_to_string(&opencode_path)?;
        let mut root: Value = serde_json::from_str(&content)?;

        let plugins = root
            .as_object_mut()
            .unwrap()
            .entry("plugins")
            .or_insert_with(|| json!([]))
            .as_array_mut()
            .unwrap();

        // Remove existing claudine-bridge entry
        plugins.retain(|p| {
            p.as_str() != Some(PLUGIN_NAME)
        });
        plugins.push(json!(PLUGIN_NAME));

        let output = serde_json::to_string_pretty(&root)?;
        atomic_write(&opencode_path, output.as_bytes())?;

        let event_count = config.events.len();
        Ok(RegistrationResult::Registered { event_count })
    }

    fn deregister(&self, config_dir: Option<&Path>) -> Result<()> {
        let opencode_path = config_path(config_dir);
        if !opencode_path.exists() {
            return Ok(());
        }

        create_backup(&opencode_path, Provider::OpenCode)?;

        // Remove plugin from opencode.json
        let content = fs::read_to_string(&opencode_path)?;
        let mut root: Value = serde_json::from_str(&content)?;

        if let Some(plugins) = root.get_mut("plugins").and_then(|p| p.as_array_mut()) {
            plugins.retain(|p| p.as_str() != Some(PLUGIN_NAME));
        }

        let output = serde_json::to_string_pretty(&root)?;
        atomic_write(&opencode_path, output.as_bytes())?;

        // Remove bridge file
        let plugin_path = plugin_dir(config_dir).join("claudine-bridge.ts");
        let _ = fs::remove_file(&plugin_path);

        Ok(())
    }

    fn is_registered(&self, config_dir: Option<&Path>) -> Result<bool> {
        let opencode_path = config_path(config_dir);
        if !opencode_path.exists() {
            return Ok(false);
        }

        let content = fs::read_to_string(&opencode_path)?;
        let root: Value = serde_json::from_str(&content)?;

        let has_plugin = root
            .get("plugins")
            .and_then(|p| p.as_array())
            .is_some_and(|arr| {
                arr.iter()
                    .any(|p| p.as_str() == Some(PLUGIN_NAME))
            });

        Ok(has_plugin)
    }

    fn registered_events(&self, config_dir: Option<&Path>) -> Result<Vec<String>> {
        if !self.is_registered(config_dir)? {
            return Ok(vec![]);
        }

        // Parse events from the bridge TypeScript file
        let bridge_path = plugin_dir(config_dir).join("claudine-bridge.ts");
        if !bridge_path.exists() {
            return Ok(vec![]);
        }

        let source = fs::read_to_string(&bridge_path)?;
        let events = extract_events_from_bridge(&source);
        Ok(events)
    }
}

/// Generate the bridge TypeScript source with event mappings.
fn generate_bridge(config: &HookerConfig) -> String {
    let entries: Vec<String> = config
        .events
        .keys()
        .map(|event| {
            let opencode_name = to_opencode_native(event);
            let snake = event.to_string();
            format!("  \"{opencode_name}\": \"{snake}\"")
        })
        .collect();

    let map_block = entries.join(",\n");
    BRIDGE_TEMPLATE.replace("{{EVENT_MAP_ENTRIES}}", &map_block)
}

/// Map Claudine events to OpenCode native event names.
fn to_opencode_native(event: &AgenticEvent) -> String {
    match event {
        AgenticEvent::BeforePrompt => "before_prompt".to_string(),
        AgenticEvent::TurnComplete => "turn_complete".to_string(),
        AgenticEvent::BeforeTool => "before_tool".to_string(),
        AgenticEvent::AfterTool => "after_tool".to_string(),
        AgenticEvent::ToolError => "tool_error".to_string(),
        AgenticEvent::SessionStart => "session_start".to_string(),
        AgenticEvent::SessionEnd => "session_end".to_string(),
        AgenticEvent::PermissionRequest => "permission_request".to_string(),
        AgenticEvent::SubagentStart => "subagent_start".to_string(),
        AgenticEvent::SubagentStop => "subagent_stop".to_string(),
        AgenticEvent::BeforeModel => "before_model".to_string(),
        AgenticEvent::AfterModel => "after_model".to_string(),
        AgenticEvent::BeforeCompact => "before_compact".to_string(),
        AgenticEvent::Notification => "notification".to_string(),
        AgenticEvent::TurnError => "turn_error".to_string(),
    }
}

/// Resolve the opencode.json config path.
fn config_path(config_dir: Option<&Path>) -> PathBuf {
    match config_dir {
        Some(dir) => dir.join("opencode.json"),
        None => {
            let home = dirs::home_dir().unwrap_or_default();
            home.join(".config")
                .join("opencode")
                .join("opencode.json")
        }
    }
}

/// Resolve the plugin directory path.
fn plugin_dir(config_dir: Option<&Path>) -> PathBuf {
    match config_dir {
        Some(dir) => dir.join("plugin"),
        None => {
            let home = dirs::home_dir().unwrap_or_default();
            home.join(".config").join("opencode").join("plugin")
        }
    }
}

/// Extract event names from bridge TypeScript source.
///
/// Parses lines like `"opencode_event": "claudine_event"` from the EVENT_MAP.
fn extract_events_from_bridge(source: &str) -> Vec<String> {
    let mut events = Vec::new();
    // Look for lines like: "before_tool": "before_tool"
    for line in source.lines() {
        let trimmed = line.trim();
        // Match pattern: "key": "value" (with or without trailing comma)
        if trimmed.contains('"') {
            if let Some(mid) = trimmed.find("\": \"") {
                if let Some(end) = trimmed[mid + 4..].find('"') {
                    let event_name = &trimmed[mid + 4..mid + 4 + end];
                    // Only add if it looks like a valid snake_case event name
                    if event_name
                        .chars()
                        .all(|c| c.is_ascii_lowercase() || c == '_')
                        && !event_name.is_empty()
                    {
                        events.push(event_name.to_string());
                    }
                }
            }
        }
    }
    events.sort();
    events.dedup();
    events
}

#[cfg(test)]
mod tests {
    use std::collections::HashMap;

    use tempfile::TempDir;

    use crate::events::{EventBinding, GlobalSettings};

    use super::*;

    fn test_config(events: Vec<AgenticEvent>) -> HookerConfig {
        let mut event_map = HashMap::new();
        for event in events {
            event_map.insert(
                event,
                EventBinding {
                    enabled: true,
                    actions: vec![],
                    matcher: None,
                    overrides: HashMap::new(),
                },
            );
        }
        HookerConfig {
            version: "1.0".to_string(),
            settings: GlobalSettings::default(),
            events: event_map,
        }
    }

    #[test]
    fn register_creates_plugin_and_config() {
        let tmp = TempDir::new().unwrap();
        let opencode = tmp.path().join("opencode.json");
        fs::write(&opencode, r#"{"plugins": []}"#).unwrap();

        let configurator = OpenCodeConfigurator;
        let config =
            test_config(vec![AgenticEvent::TurnComplete, AgenticEvent::BeforeTool]);

        let result = configurator.register(&config, Some(tmp.path())).unwrap();
        match result {
            RegistrationResult::Registered { event_count } => {
                assert_eq!(event_count, 2);
            }
            _ => panic!("expected Registered"),
        }

        // Check plugin registered in config
        let content: Value =
            serde_json::from_str(&fs::read_to_string(&opencode).unwrap()).unwrap();
        let plugins = content["plugins"].as_array().unwrap();
        assert!(plugins.iter().any(|p| p == "claudine-bridge"));
    }

    #[test]
    fn register_generates_valid_typescript_bridge() {
        let tmp = TempDir::new().unwrap();
        let opencode = tmp.path().join("opencode.json");
        fs::write(&opencode, r#"{"plugins": []}"#).unwrap();

        let configurator = OpenCodeConfigurator;
        let config = test_config(vec![AgenticEvent::TurnComplete]);
        configurator.register(&config, Some(tmp.path())).unwrap();

        let bridge_path = tmp.path().join("plugin").join("claudine-bridge.ts");
        assert!(bridge_path.exists());

        let source = fs::read_to_string(&bridge_path).unwrap();
        assert!(source.contains("claudine-bridge"));
        assert!(source.contains("execSync"));
        assert!(source.contains("claudine handle"));
        assert!(source.contains("turn_complete"));
    }

    #[test]
    fn deregister_removes_plugin() {
        let tmp = TempDir::new().unwrap();
        let opencode = tmp.path().join("opencode.json");
        fs::write(
            &opencode,
            r#"{"plugins": ["other-plugin", "claudine-bridge"]}"#,
        )
        .unwrap();

        // Create bridge file to verify cleanup
        let plugin_dir = tmp.path().join("plugin");
        fs::create_dir_all(&plugin_dir).unwrap();
        fs::write(plugin_dir.join("claudine-bridge.ts"), "// bridge").unwrap();

        let configurator = OpenCodeConfigurator;
        configurator.deregister(Some(tmp.path())).unwrap();

        let content: Value =
            serde_json::from_str(&fs::read_to_string(&opencode).unwrap()).unwrap();
        let plugins = content["plugins"].as_array().unwrap();
        assert_eq!(plugins.len(), 1);
        assert_eq!(plugins[0], "other-plugin");

        // Bridge file removed
        assert!(!plugin_dir.join("claudine-bridge.ts").exists());
    }

    #[test]
    fn is_registered_detects_plugin() {
        let tmp = TempDir::new().unwrap();
        let opencode = tmp.path().join("opencode.json");
        fs::write(&opencode, r#"{"plugins": ["claudine-bridge"]}"#).unwrap();

        let configurator = OpenCodeConfigurator;
        assert!(configurator.is_registered(Some(tmp.path())).unwrap());
    }

    #[test]
    fn is_registered_false_without_plugin() {
        let tmp = TempDir::new().unwrap();
        let opencode = tmp.path().join("opencode.json");
        fs::write(&opencode, r#"{"plugins": []}"#).unwrap();

        let configurator = OpenCodeConfigurator;
        assert!(!configurator.is_registered(Some(tmp.path())).unwrap());
    }

    #[test]
    fn skips_when_not_detected() {
        let tmp = TempDir::new().unwrap();
        let configurator = OpenCodeConfigurator;
        let config = test_config(vec![AgenticEvent::TurnComplete]);

        let result = configurator.register(&config, Some(tmp.path())).unwrap();
        assert!(matches!(
            result,
            RegistrationResult::Skipped(SkipReason::NotDetected)
        ));
    }

    #[test]
    fn preserves_existing_json_fields() {
        let tmp = TempDir::new().unwrap();
        let opencode = tmp.path().join("opencode.json");
        fs::write(
            &opencode,
            r#"{"theme": "dark", "plugins": [], "editor": "vim"}"#,
        )
        .unwrap();

        let configurator = OpenCodeConfigurator;
        let config = test_config(vec![AgenticEvent::TurnComplete]);
        configurator.register(&config, Some(tmp.path())).unwrap();

        let content: Value =
            serde_json::from_str(&fs::read_to_string(&opencode).unwrap()).unwrap();
        assert_eq!(content["theme"], "dark");
        assert_eq!(content["editor"], "vim");
    }
}
