//! The generated catalog (`messenger/docs/research/platforms/catalog.json`).
//!
//! The catalog is a serialization-only projection of validated accepted
//! research: every fact record, explicit unknowns and conflicts, provenance
//! (repository-relative document paths and Darkmatter frontmatter/body
//! hashes), freshness dates, executable eligibility with the reasons for every
//! ineligible constraint, applied overrides, and implementation assessments.
//!
//! Identical inputs produce identical bytes: every collection is sorted by a
//! stable key, embedded records are key-sorted, and nothing depends on the
//! clock or the host. Freshness is recorded as dates (`last_updated`,
//! `refresh_due`); whether a snapshot is stale is decided by readers against
//! their own `today`, so an accepted snapshot never changes merely because time
//! passed.

use serde::Serialize;
use serde_json::{Map, Value};

use super::assess::AssessmentOutcome;
use super::canonical::record_fingerprint;
use super::model::{
    AdapterId, Classification, Date, Direction, InterfaceRole, Overrides, PlatformId, Roster, State,
};
use super::diagnostics::{Diagnostic, Rule};
use super::publish::{InputEntry, SchemaEntry};
use super::validate::{ConstraintEligibility, InterfaceCoverageSummary, ValidatedDocument, refresh_due_overflow};

/// The catalog format tag.
pub const CATALOG_FORMAT: &str = "messenger-research-catalog/1";
/// The first key of every catalog: the file is generated.
pub const GENERATED_NOTICE: &str = "Generated by `messenger research generate`; do not edit.";

/// One accepted document and its Darkmatter hashes.
#[derive(Debug, Clone)]
pub struct AcceptedDocument {
    pub validated: ValidatedDocument,
    /// Darkmatter frontmatter hash (16 lowercase hex digits).
    pub frontmatter_hash: String,
    /// Darkmatter body hash: changes when substantive prose changes.
    pub body_hash: String,
}

impl AcceptedDocument {
    /// Hashes `text` (the document's bytes) with Darkmatter.
    ///
    /// ## Errors
    ///
    /// Returns the parse error message when the text has no valid frontmatter.
    pub fn new(validated: ValidatedDocument, text: &str) -> Result<Self, String> {
        let markdown =
            darkmatter::markdown::Markdown::try_from_content(text.to_string()).map_err(|error| error.to_string())?;
        Ok(Self {
            validated,
            frontmatter_hash: format!("{:016x}", markdown.hash_frontmatter(false)),
            body_hash: format!("{:016x}", markdown.hash_body(false)),
        })
    }
}

/// Everything a catalog is projected from.
#[derive(Debug, Clone, Copy)]
pub struct CatalogInputs<'a> {
    pub roster: &'a Roster,
    /// One per active roster platform, validated in `Accepted` scope.
    pub documents: &'a [AcceptedDocument],
    pub overrides: Option<&'a Overrides>,
    pub assessments: &'a [AssessmentOutcome],
    pub schema: &'a SchemaEntry,
    pub inputs: &'a [InputEntry],
}

#[derive(Debug, Clone, PartialEq, Serialize)]
pub struct Catalog {
    pub generated: &'static str,
    pub format: &'static str,
    pub schema: SchemaEntry,
    /// Every generation input with its fingerprint, sorted by path.
    pub inputs: Vec<InputEntry>,
    /// Sorted by the `platform_id` spelling.
    pub platforms: Vec<CatalogPlatform>,
    /// Implementation assessments, sorted by ID. Reporting only: nothing here
    /// changes `CapabilitySet` or delivery behavior.
    pub implementation: Vec<AssessmentOutcome>,
}

#[derive(Debug, Clone, PartialEq, Serialize)]
pub struct DocumentProvenance {
    pub path: String,
    pub frontmatter_hash: String,
    pub body_hash: String,
}

#[derive(Debug, Clone, PartialEq, Serialize)]
pub struct CatalogInterface {
    pub interface_id: String,
    pub role: InterfaceRole,
    pub direction: Direction,
    pub classification: Classification,
    pub adapters: Vec<AdapterId>,
    pub operations: Vec<String>,
}

/// One fact record with its derived knowledge summary.
#[derive(Debug, Clone, PartialEq, Serialize)]
pub struct CatalogFact {
    /// The frontmatter array, e.g. `constraints` or `text_bindings`.
    pub array: String,
    pub id: String,
    pub interface: Option<String>,
    /// `None` only for records without a knowledge block (fixtures).
    pub state: Option<State>,
    pub evidence: Vec<String>,
    pub gap: Option<String>,
    /// xxh64 of the record's canonical JSON (the assessment fingerprint input).
    pub fingerprint: String,
    /// The authored record, key-sorted.
    pub record: Value,
}

/// An override applied after validation. Both values stay visible; the
/// executable projection is always computed from the researched value.
#[derive(Debug, Clone, PartialEq, Serialize)]
pub struct AppliedOverride {
    pub id: String,
    pub fact: String,
    pub field: String,
    pub researched_value: Value,
    pub effective_value: String,
    pub evidence: Vec<String>,
    pub reason: String,
    pub author: String,
    pub review_by: Date,
}

#[derive(Debug, Clone, PartialEq, Serialize)]
pub struct CatalogPlatform {
    pub platform_id: PlatformId,
    pub name: String,
    pub document: DocumentProvenance,
    pub created: Date,
    pub last_updated: Date,
    /// `last_updated` plus the roster's refresh interval.
    pub refresh_due: Date,
    /// Sorted by `interface_id`.
    pub interfaces: Vec<CatalogInterface>,
    /// Sorted by interface; categories in category order.
    pub coverage: Vec<InterfaceCoverageSummary>,
    /// Sorted by `(array, id)`.
    pub facts: Vec<CatalogFact>,
    /// Every constraint, sorted by `(interface, operation, id)`: eligible ones
    /// with their executable projection, the rest with every reason.
    pub constraints: Vec<ConstraintEligibility>,
    /// Gap records, sorted by ID and key-sorted.
    pub gaps: Vec<Value>,
    /// Evidence sources, sorted by ID and key-sorted.
    pub sources: Vec<Value>,
    /// The document's recorded changes, sorted by ID.
    pub changes: Vec<Value>,
    /// Sorted by ID.
    pub overrides: Vec<AppliedOverride>,
}

impl Catalog {
    /// Deterministic bytes: pretty JSON, LF, trailing newline.
    pub fn to_bytes(&self) -> Vec<u8> {
        let mut bytes = serde_json::to_vec_pretty(self).expect("a catalog always serializes");
        bytes.push(b'\n');
        bytes
    }

    pub fn platform(&self, platform: PlatformId) -> Option<&CatalogPlatform> {
        self.platforms.iter().find(|entry| entry.platform_id == platform)
    }
}

/// Projects validated accepted research into the catalog.
///
/// ## Errors
///
/// An SR-ROSTER diagnostic per document whose `refresh_due` would fall after
/// 9999-12-31. Fleet validation reports the same finding, so a clean fleet
/// never reaches it.
pub fn project(inputs: CatalogInputs<'_>) -> Result<Catalog, Vec<Diagnostic>> {
    let mut platforms = Vec::new();
    let mut overflows = Vec::new();
    for accepted in inputs.documents {
        match project_platform(accepted, &inputs) {
            Ok(platform) => platforms.push(platform),
            Err(diagnostic) => overflows.push(diagnostic),
        }
    }
    if !overflows.is_empty() {
        return Err(overflows);
    }
    platforms.sort_by(|a, b| a.platform_id.as_str().cmp(b.platform_id.as_str()));
    let mut implementation = inputs.assessments.to_vec();
    implementation.sort_by(|a, b| a.id.cmp(&b.id));
    let mut catalog_inputs = inputs.inputs.to_vec();
    catalog_inputs.sort();
    Ok(Catalog {
        generated: GENERATED_NOTICE,
        format: CATALOG_FORMAT,
        schema: inputs.schema.clone(),
        inputs: catalog_inputs,
        platforms,
        implementation,
    })
}

fn project_platform(accepted: &AcceptedDocument, inputs: &CatalogInputs<'_>) -> Result<CatalogPlatform, Diagnostic> {
    let validated = &accepted.validated;
    let document = validated.document();
    let roster_platform = inputs.roster.platform(document.platform_id);
    let interval = roster_platform
        .and_then(|platform| platform.refresh_interval_days)
        .unwrap_or(inputs.roster.refresh_interval_days);
    let refresh_due = document.last_updated.checked_plus_days(interval).ok_or_else(|| Diagnostic {
        path: validated.path().clone(),
        pointer: "/last_updated".to_string(),
        rule: Rule::Roster,
        subject: Some(document.platform_id.to_string()),
        message: refresh_due_overflow(interval),
    })?;

    let mut interfaces: Vec<CatalogInterface> = document
        .interfaces
        .iter()
        .map(|interface| CatalogInterface {
            interface_id: interface.interface_id.clone(),
            role: interface.role,
            direction: interface.direction,
            classification: interface.classification,
            adapters: interface.adapters.clone(),
            operations: interface.operations.clone(),
        })
        .collect();
    interfaces.sort_by(|a, b| a.interface_id.cmp(&b.interface_id));

    let mut coverage = validated.coverage().interfaces;
    coverage.sort_by(|a, b| a.interface.cmp(&b.interface));

    let mut facts: Vec<CatalogFact> = validated
        .fact_records()
        .into_iter()
        .map(|fact| {
            let knowledge = fact.record.get("knowledge");
            let text = |value: Option<&Value>| value.and_then(Value::as_str).map(str::to_string);
            CatalogFact {
                array: fact.array,
                id: fact.id.to_string(),
                interface: text(fact.record.get("interface")),
                state: knowledge
                    .and_then(|k| k.get("state"))
                    .and_then(|state| serde_json::from_value(state.clone()).ok()),
                evidence: knowledge
                    .and_then(|k| k.get("evidence"))
                    .and_then(Value::as_array)
                    .map(|ids| ids.iter().filter_map(Value::as_str).map(str::to_string).collect())
                    .unwrap_or_default(),
                gap: text(knowledge.and_then(|k| k.get("gap"))),
                fingerprint: record_fingerprint(fact.record),
                record: sorted(fact.record),
            }
        })
        .collect();
    facts.sort_by(|a, b| (&a.array, &a.id).cmp(&(&b.array, &b.id)));

    let mut constraints = validated.eligibility();
    constraints.sort_by_key(constraint_key);

    let records = |key: &str| -> Vec<Value> {
        let mut values: Vec<Value> = validated
            .frontmatter()
            .get(key)
            .and_then(Value::as_array)
            .map(|items| items.iter().map(sorted).collect())
            .unwrap_or_default();
        values.sort_by(|a, b| a["id"].as_str().cmp(&b["id"].as_str()));
        values
    };

    let mut overrides: Vec<AppliedOverride> = inputs
        .overrides
        .map(|overrides| {
            overrides
                .overrides
                .iter()
                .filter(|entry| entry.platform_id == document.platform_id)
                .map(|entry| AppliedOverride {
                    id: entry.id.clone(),
                    fact: entry.fact.clone(),
                    field: entry.field.clone(),
                    researched_value: validated
                        .record(&entry.fact)
                        .and_then(|record| record.get(&entry.field))
                        .map(sorted)
                        .unwrap_or(Value::Null),
                    effective_value: entry.effective_value.clone(),
                    evidence: entry.evidence.clone(),
                    reason: entry.reason.clone(),
                    author: entry.author.clone(),
                    review_by: entry.review_by.clone(),
                })
                .collect()
        })
        .unwrap_or_default();
    overrides.sort_by(|a, b| a.id.cmp(&b.id));

    Ok(CatalogPlatform {
        platform_id: document.platform_id,
        name: roster_platform.map_or_else(|| document.platform_id.to_string(), |platform| platform.name.clone()),
        document: DocumentProvenance {
            path: validated.path().to_string(),
            frontmatter_hash: accepted.frontmatter_hash.clone(),
            body_hash: accepted.body_hash.clone(),
        },
        created: document.created.clone(),
        last_updated: document.last_updated.clone(),
        refresh_due,
        interfaces,
        coverage,
        facts,
        constraints,
        gaps: records("gaps"),
        sources: records("sources"),
        changes: records("changes"),
        overrides,
    })
}

fn constraint_key(entry: &ConstraintEligibility) -> (String, String, String) {
    match entry {
        ConstraintEligibility::Eligible(constraint) => {
            (constraint.interface.clone(), constraint.operation.clone(), constraint.id.clone())
        }
        ConstraintEligibility::Ineligible { id, interface, operation, .. } => {
            (interface.clone(), operation.clone(), id.clone())
        }
    }
}

/// A key-sorted copy, independent of `serde_json`'s `preserve_order`.
pub(crate) fn sorted(value: &Value) -> Value {
    match value {
        Value::Object(map) => {
            let mut keys: Vec<&String> = map.keys().collect();
            keys.sort();
            let mut out = Map::new();
            for key in keys {
                out.insert(key.clone(), sorted(&map[key]));
            }
            Value::Object(out)
        }
        Value::Array(items) => Value::Array(items.iter().map(sorted).collect()),
        scalar => scalar.clone(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::research::model::MAX_REFRESH_INTERVAL_DAYS;

    #[test]
    fn checked_plus_days_crosses_months_years_and_leap_days() {
        let date = |text: &str| Date::parse(text).expect("date");
        let plus = |text: &str, days: u32| date(text).checked_plus_days(days).expect("in range");
        assert_eq!(plus("2026-09-17", 30), date("2026-10-17"));
        assert_eq!(plus("2026-12-31", 1), date("2027-01-01"));
        assert_eq!(plus("2028-02-28", 1), date("2028-02-29"));
        assert_eq!(plus("2027-02-28", 1), date("2027-03-01"));
        assert_eq!(plus("2026-01-01", 0), date("2026-01-01"));
        assert_eq!(Date::from_unix_days(0), date("1970-01-01"));
        assert_eq!(Date::from_unix_days(20_713), date("2026-09-17"));
    }

    #[test]
    fn checked_plus_days_stops_at_the_last_four_digit_year() {
        let date = |text: &str| Date::parse(text).expect("date");
        assert_eq!(date("9999-12-30").checked_plus_days(1), Some(date("9999-12-31")));
        assert_eq!(date("9999-12-31").checked_plus_days(0), Some(date("9999-12-31")));
        assert_eq!(date("9999-12-31").checked_plus_days(1), None);
        assert_eq!(date("9999-12-01").checked_plus_days(31), None);
        assert_eq!(date("0001-01-01").checked_plus_days(u32::MAX), None);
    }

    #[test]
    fn the_largest_interval_fits_every_last_updated_through_9989_12_23() {
        let date = |text: &str| Date::parse(text).expect("date");
        assert_eq!(date("9989-12-23").checked_plus_days(MAX_REFRESH_INTERVAL_DAYS), Some(date("9999-12-31")));
        assert_eq!(date("9989-12-24").checked_plus_days(MAX_REFRESH_INTERVAL_DAYS), None);
    }

    #[test]
    fn sorted_orders_keys_at_every_depth() {
        let value = serde_json::json!({"b": {"d": 1, "c": [ {"z": 1, "a": 2} ]}, "a": null});
        let text = serde_json::to_string(&sorted(&value)).expect("json");
        assert_eq!(text, r#"{"a":null,"b":{"c":[{"a":2,"z":1}],"d":1}}"#);
    }
}
