//! Snapshot publication: a committed manifest plus a local journal.
//!
//! The accepted research snapshot (platform documents, catalog, summary) lives
//! at fixed, committed paths. `messenger/docs/research/publication.json` is the
//! single selection point: replacing it selects the new snapshot. A journal
//! with staged copies and backups under `messenger/.research-state/publication/`
//! drives rollback before that replacement and roll-forward after it, so an
//! interrupted publication always recovers to exactly the old or the new
//! snapshot. Generation and reporting read only through [`read_verified`],
//! which refuses any artifact whose bytes differ from the manifest (a hand edit,
//! a partial checkout, or a publication in flight).
//!
//! Design and per-OS evidence: the publication spike findings under
//! `messenger/features/2026-09-17-research-metadata-pipeline/spikes/publication/`.

