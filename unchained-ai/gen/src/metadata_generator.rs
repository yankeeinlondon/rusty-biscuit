//! Metadata code generator.
//!
//! Generates `metadata_generated.rs` — a static lookup table containing full
//! `ProviderModelMetadata` for all models, including pricing, parameters,
//! description, and knowledge cutoff when available.

use std::collections::HashMap;

use unchained_ai::models::identity::ModelIdentity;
use unchained_ai::models::model_metadata::{Modality, ProviderModelMetadata};

/// Generates metadata lookup table code.
pub struct MetadataGenerator {
    /// Model ID -> merged `ProviderModelMetadata`.
    entries: HashMap<String, Option<ProviderModelMetadata>>,
}

impl MetadataGenerator {
    /// Creates a new metadata generator.
    pub fn new() -> Self {
        Self {
            entries: HashMap::new(),
        }
    }

    /// Registers a model ID with optional merged metadata.
    ///
    /// When no metadata source supplied a `family`, it is
    /// filled from the id's parsed identity so the family index has full
    /// coverage regardless of upstream data quality.
    pub fn register(&mut self, model_id: String, metadata: Option<ProviderModelMetadata>) {
        let metadata = metadata.map(|mut meta| {
            if meta.family.is_none() {
                meta.family = ModelIdentity::parse(&model_id)
                    .family_or_none()
                    .map(str::to_string);
            }
            meta
        });
        self.entries.insert(model_id, metadata);
    }

    /// Merges provider-native metadata with source enrichment data.
    ///
    /// Priority: provider-native > enrichment. When both sources provide the same
    /// field (e.g., `context_window`), the provider-native value wins. Fields
    /// only available from one source are used as-is.
    pub fn merge_metadata(
        provider_native: Option<ProviderModelMetadata>,
        enrichment: Option<ProviderModelMetadata>,
    ) -> Option<ProviderModelMetadata> {
        match (provider_native, enrichment) {
            (None, None) => None,
            (Some(native), None) => Some(native),
            (None, Some(enrichment)) => Some(enrichment),
            (Some(native), Some(enrichment)) => Some(merge_native_with_enrichment(native, enrichment)),
        }
    }

    /// Generates the metadata lookup table with full fields for all models.
    pub fn generate(&self) -> String {
        let mut code = String::new();

        code.push_str("//! Generated model metadata lookup table.\n");
        code.push_str("//!\n");
        code.push_str("//! This file is auto-generated by `gen-models`. Do not edit manually.\n");
        code.push_str("//! Re-run `gen-models` to regenerate.\n\n");
        code.push_str("#![allow(deprecated)]\n\n");

        code.push_str("use std::collections::HashMap;\n");
        code.push_str("use std::sync::LazyLock;\n\n");
        code.push_str("#[allow(unused_imports)]\n");
        code.push_str(
            "use crate::models::model_metadata::{ModelMetadata, ModelModalities, Modality};\n",
        );
        code.push_str("#[allow(unused_imports)]\n");
        code.push_str("use crate::models::model_pricing::ModelPricing;\n");
        code.push_str("#[allow(unused_imports)]\n");
        code.push_str("use crate::models::model_default_parameters::ModelDefaultParameters;\n\n");

        let capacity = self.entries.len();
        code.push_str("/// Static lookup table mapping model IDs to their metadata.\n");
        code.push_str(
            "pub static MODEL_METADATA: LazyLock<HashMap<&'static str, ModelMetadata>> = LazyLock::new(|| {\n",
        );
        code.push_str(&format!(
            "    let mut m = HashMap::with_capacity({capacity});\n"
        ));

        let mut sorted_entries: Vec<_> = self.entries.iter().collect();
        sorted_entries.sort_by_key(|(k, _)| k.as_str());

        for (model_id, metadata) in sorted_entries {
            if let Some(meta) = metadata {
                code.push_str(&self.generate_entry(model_id, meta));
            }
        }

        code.push_str("    m\n");
        code.push_str("});\n");

        code
    }

    /// Generates a single entry with all metadata fields.
    fn generate_entry(&self, model_id: &str, meta: &ProviderModelMetadata) -> String {
        let mut entry = format!("    m.insert(\"{model_id}\", ModelMetadata {{\n");

        if let Some(name) = &meta.display_name {
            entry.push_str(&format!(
                "        display_name: Some(\"{}\".to_string()),\n",
                escape_string(name)
            ));
        } else {
            entry.push_str("        display_name: None,\n");
        }

        if let Some(family) = &meta.family {
            entry.push_str(&format!(
                "        family: Some(\"{}\".to_string()),\n",
                escape_string(family)
            ));
        } else {
            entry.push_str("        family: None,\n");
        }

        if let Some(ctx) = meta.context_window {
            entry.push_str(&format!("        context_window: Some({ctx}),\n"));
        } else {
            entry.push_str("        context_window: None,\n");
        }

        if let Some(max_out) = meta.max_output_tokens {
            entry.push_str(&format!("        max_output_tokens: Some({max_out}),\n"));
        } else {
            entry.push_str("        max_output_tokens: None,\n");
        }

        if let Some(mods) = &meta.modalities {
            entry.push_str("        modalities: Some(ModelModalities {\n");
            entry.push_str(&format!(
                "            input: vec![{}],\n",
                mods.input
                    .iter()
                    .map(|m| modality_variant_str(*m))
                    .collect::<Vec<_>>()
                    .join(", ")
            ));
            entry.push_str(&format!(
                "            output: vec![{}],\n",
                mods.output
                    .iter()
                    .map(|m| modality_variant_str(*m))
                    .collect::<Vec<_>>()
                    .join(", ")
            ));
            entry.push_str("        }),\n");
        } else {
            entry.push_str("        modalities: None,\n");
        }

        if meta.capabilities.is_empty() {
            entry.push_str("        capabilities: vec![],\n");
        } else {
            entry.push_str("        capabilities: vec![\n");
            for cap in &meta.capabilities {
                entry.push_str(&format!(
                    "            \"{}\".to_string(),\n",
                    escape_string(cap)
                ));
            }
            entry.push_str("        ],\n");
        }

        if let Some(desc) = &meta.description {
            entry.push_str(&format!(
                "        description: Some(\"{}\".to_string()),\n",
                escape_string(desc)
            ));
        } else {
            entry.push_str("        description: None,\n");
        }

        if let Some(pricing) = &meta.pricing {
            entry.push_str("        pricing: Some(ModelPricing {\n");
            entry.push_str(&format!(
                "            prompt_per_token: {},\n",
                format_option_f64(pricing.prompt_per_token)
            ));
            entry.push_str(&format!(
                "            completion_per_token: {},\n",
                format_option_f64(pricing.completion_per_token)
            ));
            entry.push_str(&format!(
                "            web_search_per_request: {},\n",
                format_option_f64(pricing.web_search_per_request)
            ));
            entry.push_str(&format!(
                "            input_cache_read_per_token: {},\n",
                format_option_f64(pricing.input_cache_read_per_token)
            ));
            entry.push_str("        }),\n");
        } else {
            entry.push_str("        pricing: None,\n");
        }

        if let Some(params) = &meta.supported_parameters {
            if params.is_empty() {
                entry.push_str("        supported_parameters: Some(vec![]),\n");
            } else {
                entry.push_str("        supported_parameters: Some(vec![\n");
                for p in params {
                    entry.push_str(&format!(
                        "            \"{}\".to_string(),\n",
                        escape_string(p)
                    ));
                }
                entry.push_str("        ]),\n");
            }
        } else {
            entry.push_str("        supported_parameters: None,\n");
        }

        if let Some(dp) = &meta.default_parameters {
            entry.push_str("        default_parameters: Some(ModelDefaultParameters {\n");
            entry.push_str(&format!(
                "            temperature: {},\n",
                format_option_f32(dp.temperature)
            ));
            entry.push_str(&format!(
                "            top_p: {},\n",
                format_option_f32(dp.top_p)
            ));
            entry.push_str(&format!(
                "            top_k: {},\n",
                format_option_u32(dp.top_k)
            ));
            entry.push_str(&format!(
                "            frequency_penalty: {},\n",
                format_option_f32(dp.frequency_penalty)
            ));
            entry.push_str(&format!(
                "            presence_penalty: {},\n",
                format_option_f32(dp.presence_penalty)
            ));
            entry.push_str("        }),\n");
        } else {
            entry.push_str("        default_parameters: None,\n");
        }

        if let Some(kc) = &meta.knowledge_cutoff {
            entry.push_str(&format!(
                "        knowledge_cutoff: Some(\"{}\".to_string()),\n",
                escape_string(kc)
            ));
        } else {
            entry.push_str("        knowledge_cutoff: None,\n");
        }

        if let Some(created) = meta.created {
            entry.push_str(&format!("        created: Some({created}),\n"));
        } else {
            entry.push_str("        created: None,\n");
        }

        if let Some(release_date) = &meta.release_date {
            entry.push_str(&format!(
                "        release_date: Some(\"{}\".to_string()),\n",
                escape_string(release_date)
            ));
        } else {
            entry.push_str("        release_date: None,\n");
        }

        entry.push_str("    });\n");
        entry
    }
}

impl Default for MetadataGenerator {
    fn default() -> Self {
        Self::new()
    }
}

fn merge_native_with_enrichment(
    native: ProviderModelMetadata,
    enrichment: ProviderModelMetadata,
) -> ProviderModelMetadata {
    ProviderModelMetadata {
        display_name: native.display_name.or(enrichment.display_name),
        family: native.family.or(enrichment.family),
        context_window: native.context_window.or(enrichment.context_window),
        max_output_tokens: native.max_output_tokens.or(enrichment.max_output_tokens),
        modalities: native.modalities.or(enrichment.modalities),
        capabilities: if native.capabilities.is_empty() {
            enrichment.capabilities
        } else {
            native.capabilities
        },
        description: native.description.or(enrichment.description),
        pricing: native.pricing.or(enrichment.pricing),
        supported_parameters: native.supported_parameters.or(enrichment.supported_parameters),
        default_parameters: native.default_parameters.or(enrichment.default_parameters),
        knowledge_cutoff: native.knowledge_cutoff.or(enrichment.knowledge_cutoff),
        created: native.created,
        release_date: enrichment.release_date,
    }
}

fn modality_variant_str(m: Modality) -> &'static str {
    match m {
        Modality::Text => "Modality::Text",
        Modality::Image => "Modality::Image",
        Modality::Audio => "Modality::Audio",
        Modality::Video => "Modality::Video",
        Modality::Embeddings => "Modality::Embeddings",
    }
}

fn escape_string(s: &str) -> String {
    s.replace('\\', "\\\\")
        .replace('"', "\\\"")
        .replace('\n', "\\n")
        .replace('\r', "\\r")
        .replace('\t', "\\t")
}

fn format_option_f64(v: Option<f64>) -> String {
    match v {
        Some(v) => format!("Some({v}_f64)"),
        None => "None".to_string(),
    }
}

fn format_option_f32(v: Option<f32>) -> String {
    match v {
        Some(v) => format!("Some({v}_f32)"),
        None => "None".to_string(),
    }
}

fn format_option_u32(v: Option<u32>) -> String {
    match v {
        Some(v) => format!("Some({v})"),
        None => "None".to_string(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use unchained_ai::models::model_default_parameters::ModelDefaultParameters;
    use unchained_ai::models::model_metadata::{Modality, ModelModalities};
    use unchained_ai::models::model_pricing::ModelPricing;

    fn sample_enrichment_metadata() -> ProviderModelMetadata {
        ProviderModelMetadata {
            display_name: Some("GPT-4o".to_string()),
            family: Some("gpt-4o".to_string()),
            context_window: Some(128000),
            max_output_tokens: Some(16384),
            modalities: Some(ModelModalities {
                input: vec![Modality::Text, Modality::Image],
                output: vec![Modality::Text],
            }),
            capabilities: vec![
                "function_calling".to_string(),
                "structured_output".to_string(),
            ],
            release_date: Some("2025-04-14".to_string()),
            ..Default::default()
        }
    }

    #[test]
    fn test_empty_generator() {
        let generator = MetadataGenerator::new();
        let code = generator.generate();

        assert!(code.contains("MODEL_METADATA"));
        assert!(code.contains("HashMap::with_capacity(0)"));
        assert!(code.contains("ModelPricing"));
        assert!(code.contains("ModelDefaultParameters"));
    }

    #[test]
    fn test_single_entry() {
        let mut generator = MetadataGenerator::new();

        generator.register("gpt-4o".to_string(), Some(sample_enrichment_metadata()));

        let code = generator.generate();

        assert!(code.contains("\"gpt-4o\""));
        assert!(code.contains("display_name: Some(\"GPT-4o\".to_string())"));
        assert!(code.contains("context_window: Some(128000)"));
        assert!(code.contains("Modality::Text"));
        assert!(code.contains("Modality::Image"));
        assert!(code.contains("function_calling"));
        assert!(!code.contains("..Default::default()"));
    }

    #[test]
    fn test_entry_without_metadata() {
        let mut generator = MetadataGenerator::new();
        generator.register("unknown-model".to_string(), None);

        let code = generator.generate();

        assert!(!code.contains("\"unknown-model\""));
    }

    #[test]
    fn test_escape_string() {
        assert_eq!(escape_string("hello"), "hello");
        assert_eq!(escape_string("hello\"world"), "hello\\\"world");
        assert_eq!(escape_string("line1\nline2"), "line1\\nline2");
    }

    #[test]
    fn test_modality_variant_str() {
        assert_eq!(modality_variant_str(Modality::Text), "Modality::Text");
        assert_eq!(modality_variant_str(Modality::Image), "Modality::Image");
        assert_eq!(
            modality_variant_str(Modality::Embeddings),
            "Modality::Embeddings"
        );
    }

    #[test]
    fn test_merge_none_none() {
        let result = MetadataGenerator::merge_metadata(None, None);
        assert!(result.is_none());
    }

    #[test]
    fn test_merge_native_only() {
        let native = ProviderModelMetadata {
            display_name: Some("Test".to_string()),
            context_window: Some(100000),
            pricing: Some(ModelPricing {
                prompt_per_token: Some(0.001),
                ..Default::default()
            }),
            ..Default::default()
        };
        let result = MetadataGenerator::merge_metadata(Some(native), None);
        let merged = result.unwrap();
        assert_eq!(merged.display_name.as_deref(), Some("Test"));
        assert_eq!(merged.context_window, Some(100000));
        assert!(merged.pricing.is_some());
    }

    #[test]
    fn test_merge_enrichment_only() {
        let result = MetadataGenerator::merge_metadata(None, Some(sample_enrichment_metadata()));
        let merged = result.unwrap();
        assert_eq!(merged.display_name.as_deref(), Some("GPT-4o"));
        assert_eq!(merged.family.as_deref(), Some("gpt-4o"));
        assert_eq!(merged.context_window, Some(128000));
        assert!(merged.pricing.is_none());
        assert_eq!(merged.release_date.as_deref(), Some("2025-04-14"));
    }

    #[test]
    fn test_merge_native_wins_over_enrichment() {
        let native = ProviderModelMetadata {
            display_name: Some("Native Name".to_string()),
            context_window: Some(50000),
            created: Some(1700000000),
            ..Default::default()
        };

        let result = MetadataGenerator::merge_metadata(Some(native), Some(sample_enrichment_metadata()));
        let merged = result.unwrap();

        assert_eq!(merged.display_name.as_deref(), Some("Native Name"));
        assert_eq!(merged.context_window, Some(50000));
        assert_eq!(merged.family.as_deref(), Some("gpt-4o"));
        assert_eq!(merged.capabilities.len(), 2);
        assert_eq!(merged.created, Some(1700000000));
        assert_eq!(merged.release_date.as_deref(), Some("2025-04-14"));
    }

    #[test]
    fn test_merge_enrichment_fills_gaps() {
        let native = ProviderModelMetadata {
            display_name: Some("Native Name".to_string()),
            ..Default::default()
        };

        let result = MetadataGenerator::merge_metadata(Some(native), Some(sample_enrichment_metadata()));
        let merged = result.unwrap();

        assert_eq!(merged.display_name.as_deref(), Some("Native Name"));
        assert_eq!(merged.family.as_deref(), Some("gpt-4o"));
        assert_eq!(merged.context_window, Some(128000));
    }

    #[test]
    fn test_merge_preserves_native_only_fields() {
        let native = ProviderModelMetadata {
            display_name: Some("Test".to_string()),
            description: Some("A test model.".to_string()),
            pricing: Some(ModelPricing {
                prompt_per_token: Some(0.000005),
                ..Default::default()
            }),
            supported_parameters: Some(vec!["temperature".to_string()]),
            default_parameters: Some(ModelDefaultParameters {
                temperature: Some(0.7),
                ..Default::default()
            }),
            knowledge_cutoff: Some("2024-06".to_string()),
            created: Some(1700000000),
            ..Default::default()
        };
        let result = MetadataGenerator::merge_metadata(Some(native), Some(sample_enrichment_metadata()));
        let merged = result.unwrap();

        assert_eq!(merged.description.as_deref(), Some("A test model."));
        assert!(merged.pricing.is_some());
        assert!(merged.supported_parameters.is_some());
        assert!(merged.default_parameters.is_some());
        assert_eq!(merged.knowledge_cutoff.as_deref(), Some("2024-06"));
        assert_eq!(merged.created, Some(1700000000));
    }

    #[test]
    fn test_merge_native_capabilities_used_when_non_empty() {
        let native = ProviderModelMetadata {
            display_name: Some("Test".to_string()),
            capabilities: vec!["vision".to_string()],
            ..Default::default()
        };

        let result = MetadataGenerator::merge_metadata(Some(native), Some(sample_enrichment_metadata()));
        let merged = result.unwrap();

        assert_eq!(merged.capabilities, vec!["vision"]);
    }

    #[test]
    fn test_entry_with_rich_data() {
        let mut generator = MetadataGenerator::new();

        let meta = ProviderModelMetadata {
            display_name: Some("xAI: Grok 4.3".to_string()),
            description: Some("Grok 4.3 is a reasoning model.".to_string()),
            context_window: Some(1000000),
            pricing: Some(ModelPricing {
                prompt_per_token: Some(0.00000125),
                completion_per_token: Some(0.0000025),
                web_search_per_request: Some(0.005),
                input_cache_read_per_token: Some(0.0000002),
            }),
            supported_parameters: Some(vec!["temperature".to_string(), "max_tokens".to_string()]),
            default_parameters: Some(ModelDefaultParameters {
                temperature: Some(0.7),
                top_p: Some(0.9),
                ..Default::default()
            }),
            knowledge_cutoff: Some("2025-04-30".to_string()),
            created: Some(1777591821),
            release_date: Some("2026-01-15".to_string()),
            ..Default::default()
        };

        generator.register("x-ai/grok-4.3".to_string(), Some(meta));

        let code = generator.generate();

        assert!(code.contains("MODEL_METADATA"));
        assert!(code.contains("\"x-ai/grok-4.3\""));
        assert!(code.contains("ModelMetadata"));
        assert!(code.contains("ModelPricing"));
        assert!(code.contains("ModelDefaultParameters"));
        assert!(code.contains("Some(0.00000125_f64)"));
        assert!(code.contains("Some(0.7_f32)"));
        assert!(code.contains("Some(0.9_f32)"));
        assert!(code.contains("Some(1777591821)"));
        assert!(code.contains("\"2025-04-30\""));
        assert!(code.contains("release_date: Some(\"2026-01-15\".to_string())"));
        assert!(code.contains("\"temperature\""));
        assert!(code.contains("\"max_tokens\""));
    }

    #[test]
    fn test_entry_emits_release_date_when_present() {
        let mut generator = MetadataGenerator::new();

        let meta = ProviderModelMetadata {
            display_name: Some("Released Model".to_string()),
            release_date: Some("2025-11-01".to_string()),
            ..Default::default()
        };
        generator.register("test/released".to_string(), Some(meta));

        let code = generator.generate();

        assert!(code.contains("release_date: Some(\"2025-11-01\".to_string())"));
    }

    #[test]
    fn test_format_option_f64() {
        assert_eq!(format_option_f64(Some(0.000005)), "Some(0.000005_f64)");
        assert_eq!(format_option_f64(Some(0.0)), "Some(0_f64)");
        assert_eq!(format_option_f64(None), "None");
    }

    #[test]
    fn test_format_option_f32() {
        assert_eq!(format_option_f32(Some(0.7)), "Some(0.7_f32)");
        assert_eq!(format_option_f32(None), "None");
    }

    #[test]
    fn test_format_option_u32() {
        assert_eq!(format_option_u32(Some(42)), "Some(42)");
        assert_eq!(format_option_u32(None), "None");
    }

    #[test]
    fn test_entry_emits_all_fields() {
        let mut generator = MetadataGenerator::new();

        let meta = ProviderModelMetadata {
            display_name: Some("Test Model".to_string()),
            context_window: Some(128000),
            pricing: Some(ModelPricing {
                prompt_per_token: Some(0.001),
                ..Default::default()
            }),
            description: Some("A rich model.".to_string()),
            ..Default::default()
        };
        generator.register("test/model".to_string(), Some(meta));

        let code = generator.generate();

        assert!(code.contains("pricing: Some(ModelPricing"));
        assert!(code.contains("description: Some(\"A rich model.\""));
        assert!(!code.contains("..Default::default()"));
    }
}
